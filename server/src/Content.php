    /**
     * Цена и склад товара на конкретной станции.
     *
     * Считается ДЕТЕРМИНИРОВАННО от пары «станция + товар»: цены обязаны
     * стоять на месте между запросами, иначе торговать нельзя — игрок
     * видит одно, а платит другое. Меняться они будут отдельным тиком
     * (refreshMarket), а не сами собой при каждом чтении.
     */
    public static function priceAt(array $good, string $worldType, int $stationId): array
    {
        $produces = in_array($worldType, $good['from'], true);
        $wants = in_array($worldType, $good['to'], true);

        // Шум в пределах ±0.15 базовой: две станции у одинаковых миров не
        // должны быть копией друг друга, иначе выбор порта ничего не решает.
        $n = self::hash($stationId * 7919 + crc32($good['code'])) * 0.30 - 0.15;

        $bias = 0.0;
        if ($produces) {
            $bias -= 0.60;
        }
        if ($wants) {
            $bias += 0.70;
        }

        $price = (int) round($good['base'] * (1 + $good['spread'] * ($bias + $n)));
        $price = max(1, $price);

        if ($produces) {
            $stock = round(40 + self::hash($stationId * 31 + crc32($good['code']) * 17) * 90, 1);
        } elseif ($wants) {
            // Там, где товар ждут, его на складе нет — иначе игроку нечего
            // туда везти.
            $stock = 0.0;
        } else {
            $stock = round(4 + self::hash($stationId * 13 + crc32($good['code']) * 5) * 26, 1);
        }

        return ['price' => $price, 'stock' => $stock];
    }

    /**
     * Уровень техники по виду мира: 1 — рудник, 5 — столица.
     *
     * Это не украшение карточки. От уровня зависит, что на станции вообще
     * есть: на руднике у ледяной луны не будет ни верфи, ни доски
     * подрядов, и чинить корпус там дороже. Так у портов появляется
     * разница, ради которой стоит лететь дальше.
     */
    public const TECH_BY_WORLD = [
        'ocean' => 4, 'desert' => 3, 'gas' => 2, 'rock' => 2,
        'ice' => 1, 'lava' => 1, 'moon' => 1,
    ];

    /** Свойства станции: техника, сбор, услуги. */
    public static function stationOf(string $worldType, int $bodyId, bool $homeWorld): array
    {
        $tech = self::TECH_BY_WORLD[$worldType] ?? 2;
        // Обжитой мир системы — её столица, и техника там на ступень выше.
        if ($homeWorld) {
            $tech++;
        }
        // Разброс в одну ступень: две станции у одинаковых миров не должны
        // быть копией друг друга.
        if (self::hash($bodyId * 7 + 3) > 0.72) {
            $tech++;
        }
        $tech = max(1, min(5, $tech));

        return [
            'tech' => $tech,
            // Сбор растёт с уровнем: развитый порт берёт за место дороже.
            'fee' => (int) round(10 + $tech * 14 + self::hash($bodyId * 17) * 20),
            'has_market' => 1,
            // Подряды и ремонт — там, где есть кому их выдать и чем чинить.
            'has_board' => $tech >= 2 ? 1 : 0,
            'has_repair' => $tech >= 2 ? 1 : 0,
            // Верфь — только на развитых: модули там и покупают.
            'has_outfit' => $tech >= 4 ? 1 : 0,
            'repair_rate' => round(30 - $tech * 3, 1),
            'pads' => 2 + $tech,
        ];
    }

    /**
     * Запрещённый товар лежит не везде: на обжитых мирах его не выставят.
     * Досмотра ещё нет, но место, где контрабанду вообще можно взять,
     * определиться должно уже сейчас.
     */
    public static function offeredAt(array $good, string $worldType, int $stationId): bool
    {
        if ($good['legal']) {
            return true;
        }
        return in_array($worldType, ['lava', 'rock', 'ice'], true)
            && self::hash($stationId * 101) > 0.45;
    }

    /**
     * Ровное псевдослучайное 0..1 из целого. Своё, чтобы не зависеть от
     * rand(): цены обязаны получаться одинаковыми на любой машине и в
     * любой версии PHP.
     *
     * Вход СРАЗУ обрезается до 31 бита, и это не косметика. Без обрезки
     * первое же умножение выходило за пределы 64-битного целого (индекс
     * товара доходил до 2.1e10, множитель 1.1e9 — вместе 2.3e19 при
     * пределе 9.2e18), PHP молча превращал результат в число с плавающей
     * точкой, и `&` по нему терял младшие биты. То есть ровно то
     * свойство, ради которого хеш и написан — одинаковость везде, — и
     * ломалось. Поймано по предупреждению в выводе заливки складов.
     */
    public static function hash(int $n): float
    {
        $x = (($n & 0x7fffffff) * 1103515245 + 12345) & 0x7fffffff;
        $x ^= ($x >> 13);
        $x = ($x * 1274126177) & 0x7fffffff;
        return (($x ^ ($x >> 16)) & 0xffff) / 65535.0;
    }
