<?php
/**
 * Часы мира: единые для всех.
 *
 * Орбиты планет, лун и станций считаются от одного числа — времени мира.
 * Пока игра была одиночной, это число жило в сейве и росло у каждого своё;
 * в онлайне так нельзя. Два пилота стояли в ста метрах друг от друга,
 * видели друг друга правильно, а станцию видел только один: у второго она
 * по его времени успела уехать по орбите.
 *
 * Поэтому время мира считает сервер, а клиенты его только читают. Хранится
 * не само время, а МОМЕНТ РОЖДЕНИЯ мира: иначе его пришлось бы куда-то
 * писать каждую секунду, а при остановленном сервере мир замирал бы.
 */

final class Clock
{
    /** Момент рождения мира, unix-время с долями. */
    public static function epoch(): float
    {
        $v = Schema::meta('world_epoch');
        if ($v === null || (float) $v <= 0) {
            // Заводим при первом же вопросе, а не в установке: базы
            // бывают старше этого кода, и пустое место здесь означало бы
            // мир, застрявший в нуле.
            $v = (string) microtime(true);
            Schema::setMeta('world_epoch', $v);
        }
        return (float) $v;
    }

    /** Сколько секунд миру. Это и есть время, по которому идут орбиты. */
    public static function worldTime(): float
    {
        return round(microtime(true) - self::epoch(), 3);
    }
}
