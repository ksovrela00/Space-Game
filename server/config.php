<?php
/**
 * Подключение к базе.
 *
 * Значения ровно те, что стоят в локальном XAMPP. Пароль пустой — это
 * машина разработчика, и база слушает только localhost; на боевой машине
 * этот файл заменяется своим (см. config.local.php ниже), а не правится.
 *
 * Имя базы можно перебить переменной окружения SOLAR_DB — на этом стоят
 * проверки: они работают на отдельной базе solar_trader_test и сносят её
 * целиком, и промахнуться здесь нельзя.
 */

define('MYSQLHOST', 'localhost');
define('MYSQLPORT', '3306');
define('MYSQLUSER', 'root');
define('MYSQLPASS', '');

define('MYSQLDB', getenv('SOLAR_DB') ?: 'solar_trader');

// Локальная перебивка: если файл рядом есть, он главнее. В репозитории
// его нет намеренно — у каждой машины свой.
if (is_file(__DIR__ . '/config.local.php')) {
    require __DIR__ . '/config.local.php';
}

/**
 * Часовой пояс приложения — UTC, и никакой другой.
 *
 * Сроки заданий и отметки в ленте операций пишутся временем сервера, а
 * игроки в онлайне сидят в разных поясах. Единственный способ не
 * разбираться потом, чьё «вчера» имелось в виду, — держать в базе UTC и
 * переводить в местное время только на экране.
 */
date_default_timezone_set('UTC');
