const overlay = () => document.getElementById('overlay');
const panelEl = () => document.getElementById('panel');

export function hideOverlay() {
  overlay().classList.add('hidden');
  panelEl().innerHTML = '';
}

const show = (html, buttons) => {
  const p = panelEl();
  p.innerHTML = html;
  // Панель длиннее экрана, и прокручивают её клавишами тоже — а для
  // этого браузеру нужен фокус на ней (js/core/input.js, scrollPanel).
  // Раз панель одна на все экраны, её прокрутка от прошлого открытия
  // никуда не девается: без сброса справка открывалась бы там, где её
  // бросили в прошлый раз.
  p.tabIndex = -1;
  p.scrollTop = 0;
  const box = document.createElement('div');
  for (const b of buttons) {
    const btn = document.createElement('button');
    btn.className = 'btn' + (b.ghost ? ' ghost' : '');
    btn.textContent = b.label;
    btn.addEventListener('click', b.onClick);
    box.appendChild(btn);
  }
  p.appendChild(box);
  overlay().classList.remove('hidden');
  try { p.focus({ preventScroll: true }); } catch (e) { p.focus(); }
};

export function showDocked(game) {
  const st = game.ship.dockedAt;
  const planet = st ? st.parent : null;
  const online = !!(game.player && game.player.server);
  const port = game.port;
  const hull = Math.round(game.ship.hull);

  // Ремонт стоит денег и есть не везде. Цену считаем по ставке порта —
  // ту же формулу применит сервер, и расхождение было бы обманом.
  const damage = Math.max(0, 100 - hull);
  const canRepair = online && port && port.services && port.services.repair;
  const repairCost = canRepair ? Math.ceil(damage * port.repairRate) : 0;

  const money = online
    ? `<tr><td>${L('Счёт')}</td><td class="v">${game.player.balance.toLocaleString(numLocale())} ${L('кр')}</td></tr>`
    : '';
  const portRows = online && port ? `
      <tr><td>${L('Уровень порта')}</td><td class="v">${port.tech} ${L('из 5')}</td></tr>
      <tr><td>${L('Сбор за место')}</td><td class="v">${port.fee} ${L('кр')}</td></tr>
      <tr><td>${L('Услуги')}</td><td class="v">${
        [port.services.market && 'рынок', port.services.board && 'подряды',
          port.services.repair && 'ремонт', port.services.outfit && 'верфь']
          .filter(Boolean).join(', ') || '—'}</td></tr>` : '';

  const note = online
    ? (damage > 0
      ? (canRepair
        ? L('Корпус повреждён на ') + damage + L('%. Ремонт здесь — ') + repairCost + L(' кр.')
        : L('Корпус повреждён, а чинить здесь нечем: нужен порт с мастерской.'))
      : L('Корпус цел. Порт свободен для вылета.'))
    : L('Корпус восстановлен. Порт свободен для вылета.');

  const buttons = [{ label: L('ВЫЛЕТ'), onClick: () => game.launch() }];
  if (canRepair && damage > 0) {
    buttons.push({ label: L('РЕМОНТ · ') + repairCost + L(' кр'), onClick: () => game.repair() });
  }
  buttons.push({ label: L('КАРТА СИСТЕМЫ'), ghost: true,
    onClick: () => { hideOverlay(); game.state.mode = ST.MAP; } });

  show(`
    <h1>${L('СТЫКОВКА')}</h1>
    <h2>${st ? st.name : ''}</h2>
    <table class="rows">
      <tr><td>${L('Планета')}</td><td class="v">${planet ? planet.name : '—'}</td></tr>
      <tr><td>${L('Тип')}</td><td class="v">${planet ? L(KIND_RU[planet.kind] || planet.kind) : '—'}</td></tr>
      <tr><td>${L('Радиус планеты')}</td><td class="v">${planet ? fmtDist(planet.radius) : '—'}</td></tr>
      <tr><td>${L('Высота орбиты')}</td><td class="v">${st && planet ? fmtDist(st.orbit.radius - planet.radius) : '—'}</td></tr>
      <tr><td>${L('Состояние корпуса')}</td><td class="v">${hull}%</td></tr>
      <tr><td>${L('Стыковок выполнено')}</td><td class="v">${game.stats.docks}</td></tr>
      ${money}${portRows}
    </table>
    <p class="sub">${note}</p>
  `, buttons);
}

export function showCrash(game) {
  show(`
    <h1>${L('КОРПУС РАЗРУШЕН')}</h1>
    <p class="warn">${game.crashReason || 'Столкновение на недопустимой скорости.'}</p>
    <p class="sub">${L('Страховка восстановила корабль на последней станции.')}</p>
  `, [
    { label: L('ПРОДОЛЖИТЬ'), onClick: () => game.respawn() },
  ]);
}

