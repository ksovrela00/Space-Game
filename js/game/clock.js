// Часы мира: общие для всех, подводятся на ходу.
//
// Орбиты планет, лун и станций считаются от одного числа — времени мира.
// Пока игра была одиночной, оно просто росло у каждого своё, и это ничему
// не мешало. В онлайне мешает сразу: два пилота стояли в сотне метров
// друг от друга, видели друг друга правильно, а станцию видел только
// один — у второго она по его времени уехала по орбите. Поэтому время
// мира задаёт сервер (server/src/Clock.php), а клиент идёт с ним в ногу.
//
// Подводить часы рывком нельзя: планеты и станции прыгнут по орбитам, а
// станция, к которой заходишь на стыковку, уедет из-под носа. Поэтому
// маленькое расхождение выбирается ускорением или замедлением хода, и
// только большое — рывком: там всё равно всё не на месте (так бывает
// после варпа, где мир собирается заново, и после спящей вкладки).
//
// Модуль ничего не знает ни про сеть, ни про мир: на входе два числа, на
// выходе — насколько подвинуть время в этом кадре. Отсюда и проверки в
// Node.

/** Больше этого расхождения (с) подводим рывком, а не ходом. */
export const CLOCK_SNAP = 20;

/** Насколько можно ускорить или замедлить ход часов при подтяжке. */
export const CLOCK_RATE = 0.25;

export const makeClock = () => ({ time: null, at: 0 });

/** Запомнить время мира, пришедшее с сервера. */
export function clockFromServer(clock, worldTime, now) {
  if (typeof worldTime === 'number' && Number.isFinite(worldTime)) {
    clock.time = worldTime;
    clock.at = now;
  }
  return clock;
}

/**
 * Каким время мира должно быть прямо сейчас, или null — сервера нет.
 *
 * Между снимками время досчитывается само: снимки идут пять раз в
 * секунду, а кадров шестьдесят, и ждать снимка значило бы дёргать орбиты
 * ровно так же, как дёргались бы чужие корабли.
 */
export function clockTarget(clock, now) {
  if (clock.time === null) return null;
  return clock.time + Math.max(0, now - clock.at);
}

/**
 * Насколько подвинуть время мира в этом кадре.
 *
 * Ход никогда не становится отрицательным: планеты, поехавшие по орбитам
 * назад, — это не «подвели часы», это поломка.
 */
export function clockStep(local, target, dt) {
  if (target === null || !Number.isFinite(target)) return dt;
  const err = target - local;
  if (Math.abs(err) > CLOCK_SNAP) return dt + err;
  const max = CLOCK_RATE * dt;
  return dt + Math.max(-max, Math.min(max, err));
}
