// Приближение по нажатию колеса мыши: бинокль, ×2 → ×4 → ×8 → обычный вид.
//
// Приближение СУЖАЕТ поле зрения, а не двигает камеру: в кабине это то,
// что видно в остекление, пешком — то, что видят глаза, и рамка кабины
// при этом остаётся на своём месте, а не наезжает на лицо. Сужается не
// угол, а его тангенс: картинка в середине кадра растёт ровно в столько
// раз, сколько написано, — угол, поделённый на восемь, увеличивал бы
// заметно меньше заявленного на широком поле и ровно столько же на узком.
//
// Взгляд мышью под приближением медленнее во столько же раз
// (lookScale): на ×8 прежний шаг мыши перескакивал бы то, что
// приближали рассмотреть.

/** Ступени приближения по кругу: первая — обычный вид. */
export const ZOOMS = [1, 2, 4, 8];

/** Следующая ступень по нажатию колеса; неизвестная — с обычного вида. */
export function nextZoom(k) {
  const i = ZOOMS.indexOf(k);
  return ZOOMS[(i + 1) % ZOOMS.length];
}

/** Поле зрения с приближением k, радианы. */
export const zoomFov = (fov, k) => (k > 1 ? 2 * Math.atan(Math.tan(fov / 2) / k) : fov);

/** Во сколько раз медленнее взгляд под приближением k. */
export const lookScale = (k) => (k > 1 ? 1 / k : 1);
