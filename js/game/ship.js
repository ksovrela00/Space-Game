// Корабль игрока.
//
// Скорость — настоящий ВЕКТОР со своей инерцией, а тяга и подъёмные
// движки задают лишь то, куда корабль хочет лететь. Разница между
// «хочет» и «летит» гасится с ограниченным ускорением, и отсюда всё
// поведение: разворот на скорости уводит в занос, торможение требует
// расстояния, а от удара о грунт есть что отражать — раньше вектор
// назначался напрямую, и отскакивать было нечему.
//
// Полная ньютоновщина здесь всё же не нужна: поперёк носа у движков своя
// власть (SHIP.lateral), и она достаточно велика, чтобы занос ощущался,
// но не превращал каждый манёвр в задачу по баллистике. Это осознанно
// чуть казуально.

import { v3, copy, clamp, approach, rampTo } from '../core/vec3.js';
import { makeBasis, rotateBasis } from '../core/basis.js';
import { input } from '../core/input.js';
import { HULL, REF } from './hull.js';

/**
 * Лётная модель корабля.
 *
 * ПУСТА ДО ЗАГРУЗКИ. Числа приходят из бэкенда — server/data/specs.php
 * заливается в базу, база отдаёт их маршрутом `catalog.specs`, и
 * applyShipSpec раскладывает их сюда (js/game/specs.js). Раньше они
 * стояли здесь константами, а база была их слепком; выходило, что о
 * своей скорости и своём уроне клиент сообщает серверу сам. В онлайне
 * это неверно по самой сути.
 *
 * Объект ТОТ ЖЕ САМЫЙ, а не заменяется новым: на него по ссылке смотрят
 * полтора десятка модулей (SHIP.maxSpeed), и подмена означала бы, что
 * половина игры продолжает читать старый.
 *
 * Пустой, а не со значениями «на всякий случай»: значение по умолчанию —
 * тихая ложь. Не доехали числа — корабль полетит, и никто не заметит, по
 * каким. Пустой объект даёт NaN на первом же кадре, и это видно сразу.
 */
export const SHIP = {};

/** Приехали ли характеристики. Спрашивают проверки и загрузчик. */
export const shipReady = () => typeof SHIP.maxSpeed === 'number';

// Момент инерции корпуса вокруг каждой оси — для однородного бруска он
// пропорционален сумме квадратов двух других полуразмеров (на единицу
// массы). Числа берутся из САМОЙ МОДЕЛИ текущего корпуса
// (js/game/hull.js): сменился корпус — изменилось и то, как он
// ворочается. У «Челленджера» (67 м в размахе, 65 в длину, 19 в высоту)
// рыскание почти вдвое тяжелее крена и тангажа: широкий и длинный, но
// плоский. В бэкенд они не уехали и не должны: это не настройка, а
// следствие геометрии меша.
const inertiaOf = (h) => ({ pitch: h.y ** 2 + h.z ** 2, yaw: h.x ** 2 + h.z ** 2, roll: h.x ** 2 + h.y ** 2 });

// Плечо до самой дальней точки корпуса от каждой оси, км: нос и корма
// для тангажа, концы крыльев для крена, углы крыльев для рыскания. На
// них и приходится центростремительное ускорение ω²·r, которым
// ограничено вращение (SHIP.tipAccel). Объект один, поля — текущего
// корпуса (заполняет applyShipSpec).
const armsOf = (h) => ({ pitch: Math.hypot(h.y, h.z), yaw: Math.hypot(h.x, h.z), roll: Math.hypot(h.x, h.y) });
export const TIP_ARM = { pitch: 0, yaw: 0, roll: 0 };

/**
 * КОРПУС БОЛЬШЕ — КОРАБЛЬ ДРУГОЙ. Числа модулей в бэкенде написаны для
 * корпуса, под который они рассчитаны («Челленджер», REF в
 * js/game/hull.js). На другом корпусе тот же модуль ведёт себя иначе, и
 * это следствие корпуса, а не подкрученные числа:
 *
 *   * маршевые: модуль двигателя — реактор и управление, а сопла и камеры
 *     — часть корпуса. Во сколько раз тяга корпуса больше, чем у того,
 *     под который рассчитан модуль, — thrustK в бэкенде (у «Прометея» 14:
 *     два сопла по 12.7 м на срезе), а масса — из объёма модели (в 23
 *     раза). Разгон и торможение — тяга на массу: у «Прометея» 0.6 от
 *     «Челленджера», до предела хода четыре с половиной секунды вместо
 *     двух с половиной;
 *   * форсаж — та же доля тяги сверху, и выходит на предел он во столько
 *     же раз дольше (boostRamp);
 *   * маневровые — малые сопла по оконечностям: их сила растёт с
 *     мощностью, то есть с объёмом, и на тонну массы она та же — поэтому
 *     власть поперёк носа прежняя. Момент — сила на плечо, а плечо у
 *     длинного корабля длиннее; угловое ускорение — момент на инерцию.
 *     Предел вращения задан прочностью оконечностей (tipAccel) и падает
 *     как √(1/плечо). Выход на него у «Прометея» — 1.8 с по крену, 2.5 по
 *     тангажу и 3.5 по рысканию против 1.4, 1.3 и 2.2;
 *   * приводы крупнее отвечают медленнее — клапаны, раскрутка насосов:
 *     постоянная времени маневровых и скорость перекладки тяги — как √k
 *     (k — корень кубический из отношения объёмов, у подобных тел это
 *     отношение длин), как период у подобных механических систем. Шасси
 *     выпускается так же.
 *
 * Для «Челленджера» thrustK = 1 и k = 1, и ни одно его число не меняется.
 */
export function hullScale(k, thrustK = 1) {
  const thrust = thrustK / (k * k * k);
  return { thrust, time: 1 / thrust, lag: Math.sqrt(k) };
}

// Полоса регулятора угловой скорости в постоянных времени маневровых.
// Регулятор даёт полный момент вдали от заданной скорости и
// пропорциональный — вблизи; вместе с задержкой маневровых это звено
// второго порядка, и при 3.2 постоянных его затухание 0.9: скорость
// выходит на заданную без перелёта и без раскачки.
const RCS_BAND = 3.2;

/**
 * Принять лётную модель от бэкенда.
 *
 * Кроме раскладывания чисел считает то, что из них ВЫВОДИТСЯ. Вывод
 * живёт здесь, а не на сервере, по простой причине: он опирается на
 * геометрию корпуса, а корпус — файл модели у клиента. Серверу для его
 * дела (урон, трюм, щит) эти величины не нужны вовсе.
 */
// Ключи, пришедшие с прошлой лётной моделью (см. applyShipSpec).
let specKeys = [];

export function applyShipSpec(spec) {
  // Числа, которых в НОВОЙ модели нет, обязаны уйти, а не дожить от
  // прошлой. Модель собирается из модулей в гнёздах, и снятый на верфи
  // модуль уносит свои числа с собой: продал дополнительный бак — объём
  // обязан стать прежним, продал щит — щита у корабля нет. Одно
  // Object.assign оставило бы их на месте, и корабль летал бы с баком и
  // щитом, которых у него больше нет.
  for (const k of specKeys) if (!(k in spec)) delete SHIP[k];
  specKeys = Object.keys(spec);
  Object.assign(SHIP, spec);

  // Просветы — свойство КОРПУСА, а не настройка, поэтому берутся из
  // модели (js/models/ships.js). Сменили корабль — пересчитались сами;
  // прежние 10 и 4 метра были посчитаны по старому клину и на корпусе
  // другой высоты означали бы, что днище уже в грунте.
  SHIP.gearClear = HULL.gearClear;   // высота центра корабля над грунтом на шасси, км
  SHIP.hullClear = HULL.clear;       // то же, когда корабль лежит на брюхе

  // Размер корпуса (см. hullScale): у «Челленджера» всё остаётся как есть.
  const s = hullScale(HULL.k, SHIP.thrustK > 0 ? SHIP.thrustK : 1);
  SHIP.hullK = HULL.k;
  for (const key of ['accel', 'brake']) if (SHIP[key] > 0) SHIP[key] *= s.thrust;
  if (SHIP.boostRamp > 0) SHIP.boostRamp *= s.time;
  if (SHIP.rcsLag > 0) SHIP.rcsLag *= s.lag;
  if (SHIP.throttleRate > 0) SHIP.throttleRate /= s.lag;
  if (SHIP.gearTime > 0) SHIP.gearTime *= s.lag;
  const arm = armsOf(HULL.half), armRef = armsOf(REF.half);
  const I = inertiaOf(HULL.half), Iref = inertiaOf(REF.half);
  Object.assign(TIP_ARM, arm);

  // Множитель тяги на форсаже выводится из времени разгона, а не
  // подбирается руками: поменяли boostMax или boostRamp — он пересчитался
  // сам, и обещание «полторы секунды до предела» осталось верным.
  SHIP.boostAccel = (SHIP.maxSpeed * (SHIP.boostMax - 1)) / SHIP.boostRamp / SHIP.accel;

  // Предельные угловые скорости — из размера корпуса: ω = √(a/r), где a —
  // допустимое ускорение на оконечностях (tipAccel, м/с²), r — плечо до
  // них. Старый сервер присылает сами скорости — тогда берутся они.
  if (SHIP.tipAccel > 0) {
    const a = SHIP.tipAccel / 1000;                    // км/с²
    SHIP.pitchRate = Math.sqrt(a / TIP_ARM.pitch);
    SHIP.yawRate = Math.sqrt(a / TIP_ARM.yaw);
    SHIP.rollRate = Math.sqrt(a / TIP_ARM.roll);
  }

  // Момент маневровых задан через крен (rotRamp) на том корпусе, под
  // который рассчитан модуль: там это одни и те же движки, один момент на
  // все оси, и угловые ускорения остальных осей выводятся из него —
  // M = I·ε. На другом корпусе момент оси растёт с её плечом, а ускорение
  // делится на её инерцию (см. hullScale).
  const rollRef = SHIP.tipAccel > 0 ? Math.sqrt(SHIP.tipAccel / 1000 / armRef.roll) : SHIP.rollRate;
  const torque = rollRef / SHIP.rotRamp * Iref.roll;
  for (const axis of ['pitch', 'yaw', 'roll']) {
    SHIP[axis + 'Accel'] = torque / Iref[axis] * (arm[axis] / armRef[axis]) * (Iref[axis] / I[axis]);
  }

  // Задержка маневровых и полоса регулятора (см. RCS_BAND). Без задержки
  // (старый сервер) — прежнее поведение: полный момент до самой цели.
  SHIP.rcsLag = SHIP.rcsLag > 0 ? SHIP.rcsLag : 0;
  SHIP.rcsBand = Math.max(RCS_BAND * SHIP.rcsLag, 1e-3);

  // Объём бака складывается: корпусной плюс дополнительный, если он стоит
  // в гнезде. Так же считает сервер (Fuel::model) — по этому числу он и
  // заправляет, и разойдись они, шкала показывала бы полный бак, в
  // который сервер доливает ещё.
  SHIP.fuelCap = SHIP.fuelMax + (SHIP.fuelTank > 0 ? SHIP.fuelTank : 0);

  return SHIP;
}

/**
 * Одна ось вращения: регулятор угловой скорости и маневровые с задержкой.
 *
 * Регулятор просит момент: полный, пока до заданной скорости далеко, и
 * пропорциональный на подходе (полоса SHIP.rcsBand). Маневровые выходят
 * на просимый момент с постоянной времени SHIP.rcsLag — это и есть
 * задержка между рукой и поворотом: нажал — корабль трогается не сразу,
 * отпустил — ещё какое-то время доворачивает, пока сопла не развернут
 * момент против вращения.
 *
 * Сопла «работают» (ship.rcs — их видно и слышно), пока приложен заметный
 * момент: на раскрутке и на остановке. Держать ровное вращение в пустоте
 * не стоит ничего, и там они молчат.
 */
function spinAxis(ship, axis, target, accel, dt) {
  const r = ship.rot, T = ship.torq;
  const lagK = SHIP.rcsLag > 0 ? 1 - Math.exp(-dt / SHIP.rcsLag) : 1;
  const u = clamp((target - r[axis]) / (accel * SHIP.rcsBand), -1, 1);
  T[axis] += (u - T[axis]) * lagK;
  r[axis] += T[axis] * accel * dt;
  ship.rcs[axis] = Math.abs(T[axis]) > 0.12 ? Math.sign(T[axis]) : 0;
  // Работа маневровых в пересчёте на линейную скорость, км/с — по ней
  // считается топливо (js/game/fuel.js). Сопла стоят на оконечностях
  // (плечо r = TIP_ARM), момент инерции бруска I = m·r²/3, значит сила
  // F = I·ε/r = m·r·ε/3, и Δv = r·ε/3·dt. Это сотые доли того, что уходит
  // на занос: развернуть корабль почти ничего не стоит, остановить снос
  // после разворота — стоит.
  ship.dv.rcs += Math.abs(T[axis]) * accel * TIP_ARM[axis] / 3 * dt;
}

export function makeShip() {
  const s = {
    pos: v3(),
    basis: makeBasis(),
    vel: v3(),          // мировая скорость, км/с
    speed: 0,
    throttle: 0,
    // Скорость прыжка — у стоящего привода, и читается из лётной модели
    // каждый раз, а не копируется. Корабль создаётся при разборе main.js, по
    // заводской комплектации (60 тыс. км/с), а что стоит в гнёздах, сервер
    // говорит позже (useShipEquipment): копия так и оставалась заводской, и
    // «Челленджер» с приводом II прыгал на 60 тысячах вместо 90.
    get quantumSpeed() { return SHIP.quantumSpeed; },
    boost: 1,          // заряд форсажа, 0..1
    boosting: false,    // жмут ли клавишу прямо сейчас
    // Удар в момент ВКЛЮЧЕНИЯ форсажа, 0..1. Живёт здесь по той же
    // причине, что и punch у квантового привода: это состояние модели,
    // а камера и приборы его только читают.
    boostPunch: 0,
    boostLock: false,   // заряд опустошён: ждём boostArm
    rot: { pitch: 0, yaw: 0, roll: 0 },
    // Момент маневровых по осям в долях полного, −1..1: он отстаёт от
    // просимого на задержку маневровых (SHIP.rcsLag).
    torq: { pitch: 0, yaw: 0, roll: 0 },
    // Куда сейчас работают маневровые по каждой оси: -1, 0 или +1.
    // Это состояние МОДЕЛИ, а не картинки: сопла пыхают, когда момент
    // приложен, то есть на раскрутке и на остановке. Держать постоянное
    // вращение в пустоте не стоит ничего, и пыхать там нечему.
    rcs: { pitch: 0, yaw: 0, roll: 0 },
    zeroHold: 0,        // сколько ещё держать тягу на нуле (см. SHIP.zeroDwell)
    // Фары: две лампы в носу (js/game/lamps.js). Состояние живёт здесь,
    // а не в приборах, потому что это состояние КОРАБЛЯ — его видят и
    // рендер, и сеть, и проверки.
    lights: false,
    // Гасители инерции. Включены — обычный полёт: занос поперёк носа
    // подбирают маневровые, вес держит компенсатор высоты, тяга задаёт
    // скорость. Выключены — чистая баллистика (см. updateShip).
    damp: true,
    stun: 0,            // сколько ещё лететь без управления после удара
    // Отрыв от грунта: столько секунд подъёмные движки работают на
    // полный ход сами. Толчком это сделать нельзя — набранную скорость
    // тут же съест стабилизатор, как любой другой снос; отрыв и должен
    // быть РАБОТОЙ ДВИГАТЕЛЕЙ, а не импульсом из ниоткуда.
    liftHold: 0,
    hull: SHIP.maxHull,
    shield: SHIP.maxShield,
    fuel: SHIP.fuelCap,
    // Сколько скорости набрала каждая группа сопел за ПОСЛЕДНИЙ шаг, км/с:
    // маршевые, подъёмные (с компенсатором веса), маневровые (занос и
    // вращение). Из этого считается топливо (js/game/fuel.js, burnThrust).
    dv: { main: 0, lift: 0, rcs: 0 },
    dockedAt: null,
    // Корабль зафиксирован на грунте: стойки на замках, движки
    // заглушены. Касание этого ещё не значит — фиксирует пилот.
    secured: false,
    autopilot: null,
    docking: null,
    mesh: null,
    control: { pitch: 0, yaw: 0, roll: 0, thr: 0, lift: 0, boost: 0 },
    // Ход подъёмных движков за прошлый кадр — нужен приборам.
    lift: 0,
    // Посадка: шасси (t — доля выпуска), тело, на котором стоим, и
    // посадочный компьютер.
    gear: { t: 0, out: false },
    landedAt: null,
    landing: null,
  };
  return s;
}

// Ручное управление -> control. Автопилот пишет в те же поля.
//
// mouse — нос ведёт мышь (Ctrl+Пробел, js/game/mousefly.js): тогда W/S/A/D
// носа не трогают вовсе. Складываясь с ручкой, они мешали бы ей — рука на
// клавишах тяги и крена то и дело задевает соседние.
export function readControls(ship, mouse = false) {
  const c = ship.control;
  // Клавиши и сенсорный джойстик складываются: у клавиши только три
  // положения, у джойстика — все промежуточные, и терять их нельзя.
  // Складываются, а не выбирается один источник: на планшете с
  // клавиатурой работать должны оба, и ни один не должен «выигрывать».
  const pad = input.pad;
  c.pitch = clamp((mouse ? input.axis(['ArrowUp'], ['ArrowDown'])
    : input.axis(['KeyW', 'ArrowUp'], ['KeyS', 'ArrowDown'])) + pad.pitch, -1, 1);
  // Буквы — схема WASD: A/D рыскают, Q/E кренят.
  // Стрелки — классическая схема Elite: тангаж и крен.
  c.roll = clamp(input.axis(['KeyQ', 'ArrowLeft'], ['KeyE', 'ArrowRight']) + pad.roll, -1, 1);
  c.yaw = clamp((mouse ? 0 : input.axis(['KeyA'], ['KeyD'])) + pad.yaw, -1, 1);
  c.thr = clamp(input.axis(['ControlLeft', 'ControlRight'], ['ShiftLeft', 'ShiftRight']) + pad.thr, -1, 1);
  // Вертикальный ход — отдельный канал, доступный всегда: с ним можно
  // и садиться брюхом вниз, не опуская нос, и просто держать высоту над
  // поверхностью, продолжая лететь вперёд.
  c.lift = clamp(input.axis(['KeyF'], ['KeyR']) + pad.lift, -1, 1);
  // Форсаж — именно на УДЕРЖАНИИ: отпустил, и он кончился.
  c.boost = input.isDown('Space') ? 1 : 0;
  // X и Z идут через pressed, а он читается ВСЕГДА (им управляются
  // меню). Поэтому единственный флаг блокировки полёта проверяется
  // здесь руками: без этого тяга менялась бы прямо из открытого меню.
  if (input.enabled && input.pressed('KeyX')) ship.throttle = 0;
  if (input.enabled && input.pressed('KeyZ')) ship.throttle = 1;
}

export function clearControls(ship) {
  const c = ship.control;
  c.pitch = 0; c.roll = 0; c.yaw = 0; c.thr = 0; c.lift = 0; c.boost = 0;
}

/**
 * @param dt    шаг физики, с
 * @param field тяготение под кораблём: {up, g} — местная вертикаль и
 *              ускорение свободного падения (null вне захвата тела)
 */
export function updateShip(ship, dt, field = null) {
  const c = ship.control;
  const dv = ship.dv || (ship.dv = { main: 0, lift: 0, rcs: 0 });
  dv.main = 0; dv.lift = 0; dv.rcs = 0;

  // ПУСТОЙ БАК: сопла молчат — все, и маршевые, и подъёмные, и
  // маневровые. Корабль становится телом: летит, куда летел, вращается,
  // как вращался, и в поле тяжести падает — компенсатору высоты держать
  // вес нечем. Это не наказание, а то, что значит «топливо кончилось»;
  // выход из него — аварийный буксир (server/src/Fuel.php, rescue).
  // Корабль без числа в баке (проверки, собранные до характеристик)
  // сухим не считается: бака у него просто нет.
  const dry = typeof ship.fuel === 'number' && ship.fuel <= 0;

  // Форсаж. Заряд тратится только пока клавиша зажата И есть что
  // тратить; восстанавливается всегда, когда не тратится.
  const wasBoosting = ship.boosting;
  if (ship.boost <= 0) ship.boostLock = true;
  // Снимается замок на ОТПУЩЕННОЙ клавише и с накопленным зарядом.
  else if (ship.boostLock && !c.boost && ship.boost >= SHIP.boostArm) ship.boostLock = false;
  ship.boosting = c.boost > 0 && !ship.boostLock && ship.boost > 0 && ship.stun <= 0 && !dry;
  // Рывок засчитывается на переходе «не жал -> поехали», а не на
  // удержании: держать клавишу можно десять секунд, а рвёт один раз.
  // Гаснет он с тем же темпом, что у привода, — это один и тот же приём.
  //
  // Затухание идёт ПЕРЕД выставлением: иначе кадр, в котором рывок
  // возник, тут же его и подъедает, и вместо единицы наружу уходит 0.96.
  if (ship.boostPunch > 0) ship.boostPunch = Math.max(0, ship.boostPunch - dt * 2.2);
  if (ship.boosting && !wasBoosting) ship.boostPunch = 1;
  if (ship.boosting) ship.boost = Math.max(0, ship.boost - dt / SHIP.boostBurn);
  else ship.boost = Math.min(1, ship.boost + dt / SHIP.boostFill);
  const boost = ship.boosting ? SHIP.boostMax : 1;

  // Тяга от -1 (полный назад) до +1. Ноль — с защёлкой: сбрасывая тягу,
  // корабль на нём останавливается и только при дальнейшем удержании
  // Ctrl трогается назад.
  let thr = ship.throttle + c.thr * SHIP.throttleRate * dt;
  if (ship.throttle > 0 && thr <= 0) { thr = 0; ship.zeroHold = SHIP.zeroDwell; }
  else if (ship.throttle === 0 && c.thr < 0) {
    ship.zeroHold -= dt;
    if (ship.zeroHold > 0) thr = 0;
  } else if (c.thr >= 0) ship.zeroHold = 0;
  ship.throttle = clamp(thr, -1, 1);

  // Оглушение после удара: управления нет, вращение просто затухает —
  // корабль кувыркается по инерции.
  const stunned = ship.stun > 0;
  if (stunned) ship.stun = Math.max(0, ship.stun - dt);

  const r = ship.rot;
  const q = ship.rcs;
  if (!ship.torq) ship.torq = { pitch: 0, yaw: 0, roll: 0 };
  if (stunned) {
    const k = Math.max(0, 1 - SHIP.tumbleDamp * dt);
    r.pitch *= k; r.yaw *= k; r.roll *= k;
    q.pitch = q.yaw = q.roll = 0;       // управления нет — и сопла молчат
    ship.torq.pitch = ship.torq.yaw = ship.torq.roll = 0;
  } else if (dry) {
    // Вращение без маневровых ничем не гасится: оно просто продолжается.
    q.pitch = q.yaw = q.roll = 0;
    ship.torq.pitch = ship.torq.yaw = ship.torq.roll = 0;
  } else {
    // Ручка задаёт угловую СКОРОСТЬ, маневровые дают МОМЕНТ — с
    // задержкой и с регулятором, который доводит скорость до заданной
    // (spinAxis).
    spinAxis(ship, 'pitch', c.pitch * SHIP.pitchRate, SHIP.pitchAccel, dt);
    spinAxis(ship, 'yaw', c.yaw * SHIP.yawRate, SHIP.yawAccel, dt);
    spinAxis(ship, 'roll', c.roll * SHIP.rollRate, SHIP.rollAccel, dt);
  }
  rotateBasis(ship.basis, r.pitch * dt, r.yaw * dt, r.roll * dt);

  // Оглушённый корабль — просто тело в поле тяжести: ни тяги, ни
  // стабилизации. Именно здесь живёт отскок.
  if (stunned) {
    if (field) {
      ship.vel.x -= field.up.x * field.g * dt;
      ship.vel.y -= field.up.y * field.g * dt;
      ship.vel.z -= field.up.z * field.g * dt;
    }
    ship.speed = Math.hypot(ship.vel.x, ship.vel.y, ship.vel.z);
    ship.pos.x += ship.vel.x * dt;
    ship.pos.y += ship.vel.y * dt;
    ship.pos.z += ship.vel.z * dt;
    return;
  }

  // --- Двигатели, тяготение и гашение заноса.
  //
  // Никакой «заданной скорости» тут больше нет: есть ускорения, и они
  // складываются. Аркадного в модели остаётся одно — маневровые движки
  // гасят снос поперёк носа, иначе каждый разворот пришлось бы
  // отрабатывать вручную, как в орбитальном симуляторе.
  //
  // ШАССИ НЕ МЕНЯЕТ УПРАВЛЕНИЕ. Оно меняет одно — предел скорости.
  //
  // Раньше его выпуск переключал модель полёта целиком: выключался
  // компенсатор высоты (корабль начинал проваливаться сам), а главные
  // движки переставали толкать вверх и работали только по горизонту.
  // Задумано это было как «почувствовать вес на посадке», а на деле
  // читалось как поломка: одна клавиша — и корабль перестаёт слушаться
  // так, как слушался секунду назад. Ни один аппарат от выпуска стоек
  // так себя не ведёт.
  //
  // Теперь компенсатор высоты работает ВСЕГДА: движки держат корабль
  // против местной тяжести, и с нулевой ручкой он висит на месте на
  // любой высоте и с любым шасси. Тяжесть от этого не исчезает — она
  // по-прежнему задаёт силу подъёмных движков (SHIP.liftTWR), решает
  // исход удара и работает в полную силу, пока корабль оглушён (см.
  // выше: там нет ни тяги, ни стабилизации).
  const f = ship.basis.fwd, u = ship.basis.up;
  const gearOut = !!(ship.gear && ship.gear.t > 0.02);
  const up = field ? field.up : null;
  const g = field ? field.g : 0;

  // Ось подъёмных движков — «верх» самого корабля: ровно то, куда они
  // толкают. Вертикаль считается отдельным каналом, пока отклонена
  // ручка: иначе тяга движков бессмысленна — гашение заноса видит
  // набранную вертикальную скорость как снос и стирает её в следующем же
  // кадре (0.5 км/с² против 0.004).
  //
  // Отпустил ручку — канал снова общий, и набранный ход гасится, как
  // любой другой снос. Это и есть «компенсатор высоты»: он держит и вес,
  // и саму высоту. Так же ведёт себя стабилизатор по горизонтали, и так
  // же корабль вёл себя с убранным шасси всегда.
  const la = u;
  // На отрыве движки какое-то время работают сами: см. ship.liftHold.
  if (ship.liftHold > 0) ship.liftHold = Math.max(0, ship.liftHold - dt);
  const lift = dry ? 0 : (ship.liftHold > 0 ? 1 : c.lift);
  const liftOn = lift !== 0;

  // Автоматика летает ТОЛЬКО с гасителями. Докинг-компьютер и
  // посадочный задают вектор скорости напрямую (js/game/pilot.js) —
  // рассчитывать, что этот вектор кто-то выдержит, они могут лишь пока
  // занос подбирают маневровые. Поэтому включение тут, в модели, а не в
  // клавишах: автоматику заводит и сеть, и меню, а гасители нужны ей
  // всегда.
  if (ship.docking || ship.landing || ship.autopilot) ship.damp = true;
  // Гасители — это работа сопел, и без топлива их нет: модель та же, что
  // с выключенными, только без тяги. Выбор пилота (ship.damp) при этом не
  // трогаем — заправился, и всё вернулось, как было.
  const damp = ship.damp && !dry;

  // Направление тяги — всегда нос, независимо от шасси.
  const fx = f.x, fy = f.y, fz = f.z;

  // Сила подъёмных движков привязана к местной тяжести (SHIP.liftTWR),
  // вдали от тел — постоянная. Нужна обоим режимам, поэтому считается
  // до развилки.
  const liftAcc = Math.max(SHIP.liftMin, g * SHIP.liftTWR) * lift;
  ship.lift = liftAcc;

  // Предел скорости и ход вдоль носа — тоже общие.
  const lim = SHIP.maxSpeed * (gearOut ? SHIP.gearSpeed : 1) * boost;
  const cur = ship.vel.x * fx + ship.vel.y * fy + ship.vel.z * fz;
  const aBoost = ship.boosting ? SHIP.boostAccel : 1;

  if (!damp) {
    // --- ГАСИТЕЛИ ИНЕРЦИИ СНЯТЫ ---------------------------------------
    //
    // Здесь выключено разом всё, что делает модель аркадной:
    //
    //   * тяга даёт УСКОРЕНИЕ, а не заданную скорость — отпустил, и
    //     корабль несёт дальше, а не тормозит;
    //   * занос поперёк носа никто не подбирает — нос можно отвернуть от
    //     вектора скорости и лететь боком, что и есть весь смысл режима;
    //   * компенсатор высоты не держит вес, и в захвате тела корабль
    //     ПАДАЕТ.
    //
    // Расчёт тот же самый, что работает после удара о грунт (см. stunned
    // выше), с одной разницей: управление никуда не делось.
    //
    // Предел скорости при этом остаётся пределом ДВИГАТЕЛЯ: дальше него
    // он не толкает. Но и не тормозит — набранное сверх предела
    // (форсажем, тяготением, отскоком) корабль несёт сам.
    let step = dry ? 0 : SHIP.accel * aBoost * ship.throttle * dt;
    const limF = lim, limB = lim * SHIP.reverse;
    if (step > 0) step = Math.max(0, Math.min(step, limF - cur));
    else if (step < 0) step = Math.min(0, Math.max(step, -limB - cur));
    ship.vel.x += fx * step;
    ship.vel.y += fy * step;
    ship.vel.z += fz * step;
    dv.main += Math.abs(step);

    // Подъёмные движки — такая же чистая тяга, вдоль «верха» корпуса.
    if (liftOn) {
      ship.vel.x += la.x * liftAcc * dt;
      ship.vel.y += la.y * liftAcc * dt;
      ship.vel.z += la.z * liftAcc * dt;
      dv.lift += Math.abs(liftAcc) * dt;
    }

    // И тяжесть. В обычном режиме её не видно вовсе — вес держат
    // движки; здесь держать нечем, и это ровно то, ради чего гасители
    // снимают у поверхности: свободное падение, разгон по орбите,
    // гравитационный манёвр.
    if (field) {
      ship.vel.x -= up.x * g * dt;
      ship.vel.y -= up.y * g * dt;
      ship.vel.z -= up.z * g * dt;
    }
  } else {

  // Главные движки: разгон до скорости, заданной тягой. С выпущенным
  // шасси предел ниже — на нём не летают.
  //
  // Считается это ДО отделения вертикали, по полной скорости: иначе
  // предел не видит того, что корабль летит вниз, и продолжает
  // разгонять его вдоль носа — вертикальная скорость при этом растёт
  // без всякого предела. Так корабль и уходил сквозь луну.
  const target = ship.throttle * lim * (ship.throttle < 0 ? SHIP.reverse : 1);
  const aLim = (Math.abs(target) > Math.abs(cur) ? SHIP.accel * aBoost : SHIP.brake) * dt;
  const step = clamp(target - cur, -aLim, aLim);
  ship.vel.x += fx * step;
  ship.vel.y += fy * step;
  ship.vel.z += fz * step;
  dv.main += Math.abs(step);

  // Подъёмные с компенсатором: вес держат они же, и работа у них — сумма
  // того, что держит вес, и того, что просит ручка. Складываются ВЕКТОРЫ:
  // вес — по местной вертикали, ход ручки — по «верху» корпуса, и на
  // снижении (F) движки тянут меньше веса, а не больше.
  {
    const gx = up ? up.x * g : 0, gy = up ? up.y * g : 0, gz = up ? up.z * g : 0;
    const lx = gx + la.x * liftAcc, ly = gy + la.y * liftAcc, lz = gz + la.z * liftAcc;
    dv.lift += Math.hypot(lx, ly, lz) * dt;
  }

  // Теперь отделяем вертикаль — её гасить нечем, кроме тяги и подъёмных.
  let vUp = 0;
  if (liftOn) {
    vUp = ship.vel.x * la.x + ship.vel.y * la.y + ship.vel.z * la.z;
    ship.vel.x -= la.x * vUp; ship.vel.y -= la.y * vUp; ship.vel.z -= la.z * vUp;
  }

  // Гашение заноса: всё, что не вдоль тяги.
  //
  // Ось гашения — нос, но пока вертикаль вынесена в свой канал, брать
  // надо его ГОРИЗОНТАЛЬНУЮ проекцию. Иначе выходит храповик: гашение
  // доворачивает скорость на нос, нос чуть задран, у скорости появляется
  // вертикальная составляющая — а её тут же уносит в отдельный канал, где
  // её уже ничем не гасят. Следующий кадр добавляет ещё столько же. На
  // сорока метрах в секунду корабль так набирал полсотни метров высоты
  // в минуту, сам по себе.
  let gx = fx, gy = fy, gz = fz;
  if (liftOn) {
    const fu = fx * la.x + fy * la.y + fz * la.z;
    gx -= la.x * fu; gy -= la.y * fu; gz -= la.z * fu;
    const gl = Math.hypot(gx, gy, gz);
    // Нос смотрит в зенит или в надир: горизонтальной оси нет, и гасить
    // занос не по чему — вся скорость и так вертикальная.
    if (gl > 0.08) { gx /= gl; gy /= gl; gz /= gl; } else { gx = gy = gz = 0; }
  }
  const dot0 = ship.vel.x * gx + ship.vel.y * gy + ship.vel.z * gz;
  const px = ship.vel.x - gx * dot0, py = ship.vel.y - gy * dot0, pz = ship.vel.z - gz * dot0;
  const perp = Math.hypot(px, py, pz);
  if (perp > 1e-9) {
    const k = Math.min(1, SHIP.lateral * dt / perp);
    ship.vel.x -= px * k;
    ship.vel.y -= py * k;
    ship.vel.z -= pz * k;
    dv.rcs += perp * k;
  }

  if (liftOn) {
    // Вес в точности гасит компенсатор высоты, и движки разгоняют
    // корабль по вертикали — скорость КОПИТСЯ, как и любая другая.
    // Рядом с телом в дело идёт только та часть тяги, что смотрит вверх:
    // накренился — и подъёмные толкают больше вбок, чем вверх.
    vUp += liftAcc * dt;
    ship.vel.x += la.x * vUp; ship.vel.y += la.y * vUp; ship.vel.z += la.z * vUp;
  }

  }

  ship.speed = Math.hypot(ship.vel.x, ship.vel.y, ship.vel.z);
  if (ship.speed < 1e-5) {
    ship.vel.x = ship.vel.y = ship.vel.z = 0;
    ship.speed = 0;
  }

  ship.pos.x += ship.vel.x * dt;
  ship.pos.y += ship.vel.y * dt;
  ship.pos.z += ship.vel.z * dt;
}

// Мгновенно поставить корабль в точку с заданной ориентацией.
export function placeShip(ship, pos, basis) {
  copy(ship.pos, pos);
  if (basis) {
    copy(ship.basis.right, basis.right);
    copy(ship.basis.up, basis.up);
    copy(ship.basis.fwd, basis.fwd);
  }
  ship.speed = 0;
  ship.vel.x = ship.vel.y = ship.vel.z = 0;
  ship.throttle = 0;
  ship.boostPunch = 0;
  ship.boostLock = false;
  ship.zeroHold = 0;
  ship.stun = 0;
  // Гасители включаются сами: корабль ставят в точку либо при вылете,
  // либо после крушения, и в обоих случаях лететь по инерции — не то,
  // чего ждут.
  ship.damp = true;
  ship.lift = 0;
  ship.rot.pitch = ship.rot.yaw = ship.rot.roll = 0;
  // И момент маневровых: он отстаёт от просимого (SHIP.rcsLag), и без
  // этого сопла ещё секунду гасили бы вращение, которого уже нет.
  if (ship.torq) ship.torq.pitch = ship.torq.yaw = ship.torq.roll = 0;
  if (ship.rcs) ship.rcs.pitch = ship.rcs.yaw = ship.rcs.roll = 0;
}
