// Корабль игрока.
//
// Скорость — настоящий ВЕКТОР со своей инерцией, а тяга и подъёмные
// движки задают лишь то, куда корабль хочет лететь. Разница между
// «хочет» и «летит» гасится с ограниченным ускорением, и отсюда всё
// поведение: разворот на скорости уводит в занос, торможение требует
// расстояния, а от удара о грунт есть что отражать — раньше вектор
// назначался напрямую, и отскакивать было нечему.
//
// Полная ньютоновщина здесь всё же не нужна: поперёк носа у движков своя
// власть (SHIP.lateral), и она достаточно велика, чтобы занос ощущался,
// но не превращал каждый манёвр в задачу по баллистике. Это осознанно
// чуть казуально.

import { v3, copy, clamp, approach, rampTo } from '../core/vec3.js';
import { makeBasis, rotateBasis } from '../core/basis.js';
import { input } from '../core/input.js';
import { GEAR_CLEAR, HULL_CLEAR, HULL_HALF } from '../models/ships.js';

export const SHIP = {
  maxSpeed: 1.2,      // км/с — обычный полёт, без форсажа
  // Задний ход — маневровый режим, а не полёт: те же движки работают
  // против своей геометрии, и тяги у них там заметно меньше.
  reverse: 0.15,      // доля максимальной скорости на заднем ходу
  // Пауза на нуле при сбросе тяги. Без неё остановиться нельзя: тяга
  // проскакивает ноль и корабль сразу ползёт назад. С паузой ноль
  // ощущается как защёлка — задержал Ctrl дольше, поехал назад.
  zeroDwell: 0.45,    // с
  accel: 0.45,        // км/с² — разгон вдоль носа
  brake: 0.75,        // торможение вдоль носа
  // Форсаж — на удержании клавиши, с расходуемым зарядом. Он не про
  // перелёты (для них есть квантовый привод), а про то, чтобы быстрее
  // оторваться от поверхности и резче маневрировать у станции.
  boostMax: 3,        // во сколько раз растёт предел скорости
  // Форсаж поднимает не только предел, но и ТЯГУ — иначе до тройной
  // скорости корабль полз бы восемь секунд, и рывка не чувствовалось бы
  // вовсе. Задаётся при этом время разгона, а не множитель: полторы
  // секунды — это то, что чувствует игрок, а во сколько раз для этого
  // надо поднять тягу, дело арифметики (см. boostAccel ниже).
  boostRamp: 1.5,     // с — с обычного предела до форсажного
  boostBurn: 10,      // с — полный заряд на удержании
  boostFill: 15,      // с — восстановление с нуля
  // Опустошив заряд, форсаж запирается до тех пор, пока клавишу не
  // ОТПУСТЯТ и не накопится столько заряда. Без замка на зажатой
  // клавише он трещит: заряд капает и тут же тратится, форсаж
  // включается через кадр — и корабль вечно идёт в полтора раза быстрее
  // предела, не платя за это ничем. Замка «по накоплению» мало: он даёт
  // то же самое, только циклами.
  boostArm: 0.25,
  // Скорость квантового прыжка. Живёт здесь, а не в quantum.js, потому
  // что это характеристика КОРАБЛЯ: появятся другие корпуса — у каждого
  // будет своя.
  quantumSpeed: 60000,   // км/с
  // Власть движков ПОПЕРЁК носа: ею гасится занос после разворота.
  // Меньше — дольше несёт боком; больше — инерции не чувствуется вовсе.
  lateral: 0.5,       // км/с²
  // После удара о грунт корабль на это время теряет управление и летит
  // свободно — только тяготение и то, что осталось от скорости. Без
  // паузы отскока не видно: стабилизация гасит его за десятую долю
  // секунды, и удар читается как мгновенная остановка.
  stunMin: 0.35,      // с — самый лёгкий удар
  stunMax: 1.4,       // с
  tumbleDamp: 0.6,    // 1/с — как быстро затухает кувырок, пока оглушены
  // Предельные угловые скорости, рад/с. Крен быстрее всех: вокруг
  // продольной оси у корпуса меньше всего инерции, и так у всех
  // самолётов и кораблей.
  pitchRate: 0.85,
  yawRate: 0.55,
  rollRate: 1.6,
  // Маневровые двигатели дают МОМЕНТ, а не угловую скорость. Поэтому
  // вращение раскручивается и останавливается с постоянным угловым
  // ускорением, а не экспонентой: экспонента в первый же миг выдаёт
  // максимальное ускорение, и корабль дёргается — от этого он и
  // казался игрушечным, хотя выход на полную скорость занимал те же
  // доли секунды.
  //
  // Задаётся время, а не ускорение (тот же приём, что у форсажа), и
  // только для крена: остальные оси считаются из момента инерции
  // корпуса — он у них другой, и раскручиваться они обязаны иначе.
  rotRamp: 0.7,       // с — за столько крен выходит на свой предел
  throttleRate: 0.7,  // единиц тяги в секунду
  maxHull: 100,

  // Посадочное оборудование
  gearTime: 2.4,      // секунды на выпуск или уборку шасси
  gearSpeed: 0.35,    // доля максимальной скорости с выпущенным шасси
  // Просветы — свойство КОРПУСА, а не физики, поэтому берутся из
  // модели (js/models/ships.js). Сменили корабль — пересчитались сами;
  // прежние 10 и 4 метра были посчитаны по старому клину и на корпусе
  // другой высоты означали бы, что днище уже в грунте.
  gearClear: GEAR_CLEAR,   // высота центра корабля над грунтом на шасси, км
  hullClear: HULL_CLEAR,   // то же, когда корабль лежит на брюхе
  // Подъёмные движки (R/F) дают ТЯГУ, а не заданную скорость: с
  // настоящей гравитацией «задать вертикальную скорость» нельзя, её
  // можно только создать двигателем. Сила привязана к местной тяжести —
  // полный ход даёт втрое больше веса, то есть зависание приходится
  // примерно на треть хода на любом теле. Это сознательное упрощение:
  // иначе на луне ручка была бы неуправляемо чувствительной, а на
  // тяжёлой планете её не хватало бы.
  liftTWR: 3,         // во сколько раз полная тяга движков больше веса
  liftMin: 0.004,     // км/с² — тяга вдали от тел, где веса нет вовсе
  // Компенсатор высоты работает ВСЕГДА и в точности гасит вес: корабль
  // не проваливается ни с убранным шасси, ни с выпущенным. Шасси меняет
  // только предел скорости (gearSpeed) — см. updateShip.
};

// Множитель тяги на форсаже выводится из времени разгона, а не
// подбирается руками: поменяли boostMax или boostRamp — он пересчитался
// сам, и обещание «полторы секунды до предела» осталось верным.
SHIP.boostAccel = (SHIP.maxSpeed * (SHIP.boostMax - 1)) / SHIP.boostRamp / SHIP.accel;

// Момент инерции корпуса вокруг каждой оси — для однородного бруска он
// пропорционален сумме квадратов двух других полуразмеров. Числа берутся
// из САМОЙ МОДЕЛИ (js/models/ships.js), поэтому сменится корпус —
// изменится и то, как он ворочается. У здешнего корабля (67 м в размахе,
// 65 в длину, 19 в высоту) рыскание почти вдвое тяжелее крена и тангажа:
// широкий и длинный, но плоский.
const I_PITCH = HULL_HALF.y ** 2 + HULL_HALF.z ** 2;
const I_YAW = HULL_HALF.x ** 2 + HULL_HALF.z ** 2;
const I_ROLL = HULL_HALF.x ** 2 + HULL_HALF.y ** 2;

// Момент маневровых один на все оси: это одни и те же движки. Задан он
// через крен (rotRamp), а угловые ускорения остальных осей из него и
// выводятся — M = I·ε.
SHIP.rollAccel = SHIP.rollRate / SHIP.rotRamp;
const TORQUE = SHIP.rollAccel * I_ROLL;
SHIP.pitchAccel = TORQUE / I_PITCH;
SHIP.yawAccel = TORQUE / I_YAW;

// В какую сторону работают сопла: знак момента, который сейчас нужен.
// Ноль, если угловая скорость уже та, которую просят, — тогда момент не
// нужен вовсе.
const torqueDir = (cur, target, step) =>
  (Math.abs(target - cur) < step * 0.05 ? 0 : Math.sign(target - cur));

export function makeShip() {
  const s = {
    pos: v3(),
    basis: makeBasis(),
    vel: v3(),          // мировая скорость, км/с
    speed: 0,
    throttle: 0,
    quantumSpeed: SHIP.quantumSpeed,
    boost: 1,           // заряд форсажа, 0..1
    boosting: false,    // жмут ли клавишу прямо сейчас
    // Удар в момент ВКЛЮЧЕНИЯ форсажа, 0..1. Живёт здесь по той же
    // причине, что и punch у квантового привода: это состояние модели,
    // а камера и приборы его только читают.
    boostPunch: 0,
    boostLock: false,   // заряд опустошён: ждём boostArm
    rot: { pitch: 0, yaw: 0, roll: 0 },
    // Куда сейчас работают маневровые по каждой оси: -1, 0 или +1.
    // Это состояние МОДЕЛИ, а не картинки: сопла пыхают, когда момент
    // приложен, то есть на раскрутке и на остановке. Держать постоянное
    // вращение в пустоте не стоит ничего, и пыхать там нечему.
    rcs: { pitch: 0, yaw: 0, roll: 0 },
    zeroHold: 0,        // сколько ещё держать тягу на нуле (см. SHIP.zeroDwell)
    stun: 0,            // сколько ещё лететь без управления после удара
    hull: SHIP.maxHull,
    dockedAt: null,
    autopilot: null,
    docking: null,
    mesh: null,
    control: { pitch: 0, yaw: 0, roll: 0, thr: 0, lift: 0, boost: 0 },
    // Ход подъёмных движков за прошлый кадр — нужен приборам.
    lift: 0,
    // Посадка: шасси (t — доля выпуска), тело, на котором стоим, и
    // посадочный компьютер.
    gear: { t: 0, out: false },
    landedAt: null,
    landing: null,
  };
  return s;
}

// Ручное управление -> control. Автопилот пишет в те же поля.
export function readControls(ship) {
  const c = ship.control;
  c.pitch = input.axis(['KeyW', 'ArrowUp'], ['KeyS', 'ArrowDown']);
  // Буквы — схема WASD: A/D рыскают, Q/E кренят.
  // Стрелки — классическая схема Elite: тангаж и крен.
  c.roll = input.axis(['KeyQ', 'ArrowLeft'], ['KeyE', 'ArrowRight']);
  c.yaw = input.axis(['KeyA'], ['KeyD']);
  c.thr = input.axis(['ControlLeft', 'ControlRight'], ['ShiftLeft', 'ShiftRight']);
  // Вертикальный ход — отдельный канал, доступный всегда: с ним можно
  // и садиться брюхом вниз, не опуская нос, и просто держать высоту над
  // поверхностью, продолжая лететь вперёд.
  c.lift = input.axis(['KeyF'], ['KeyR']);
  // Форсаж — именно на УДЕРЖАНИИ: отпустил, и он кончился.
  c.boost = input.isDown('Space') ? 1 : 0;
  if (input.pressed('KeyX')) ship.throttle = 0;
  if (input.pressed('KeyZ')) ship.throttle = 1;
}

export function clearControls(ship) {
  const c = ship.control;
  c.pitch = 0; c.roll = 0; c.yaw = 0; c.thr = 0; c.lift = 0; c.boost = 0;
}

/**
 * @param dt    шаг физики, с
 * @param field тяготение под кораблём: {up, g} — местная вертикаль и
 *              ускорение свободного падения (null вне захвата тела)
 */
export function updateShip(ship, dt, field = null) {
  const c = ship.control;

  // Форсаж. Заряд тратится только пока клавиша зажата И есть что
  // тратить; восстанавливается всегда, когда не тратится.
  const wasBoosting = ship.boosting;
  if (ship.boost <= 0) ship.boostLock = true;
  // Снимается замок на ОТПУЩЕННОЙ клавише и с накопленным зарядом.
  else if (ship.boostLock && !c.boost && ship.boost >= SHIP.boostArm) ship.boostLock = false;
  ship.boosting = c.boost > 0 && !ship.boostLock && ship.boost > 0 && ship.stun <= 0;
  // Рывок засчитывается на переходе «не жал -> поехали», а не на
  // удержании: держать клавишу можно десять секунд, а рвёт один раз.
  // Гаснет он с тем же темпом, что у привода, — это один и тот же приём.
  //
  // Затухание идёт ПЕРЕД выставлением: иначе кадр, в котором рывок
  // возник, тут же его и подъедает, и вместо единицы наружу уходит 0.96.
  if (ship.boostPunch > 0) ship.boostPunch = Math.max(0, ship.boostPunch - dt * 2.2);
  if (ship.boosting && !wasBoosting) ship.boostPunch = 1;
  if (ship.boosting) ship.boost = Math.max(0, ship.boost - dt / SHIP.boostBurn);
  else ship.boost = Math.min(1, ship.boost + dt / SHIP.boostFill);
  const boost = ship.boosting ? SHIP.boostMax : 1;

  // Тяга от -1 (полный назад) до +1. Ноль — с защёлкой: сбрасывая тягу,
  // корабль на нём останавливается и только при дальнейшем удержании
  // Ctrl трогается назад.
  let thr = ship.throttle + c.thr * SHIP.throttleRate * dt;
  if (ship.throttle > 0 && thr <= 0) { thr = 0; ship.zeroHold = SHIP.zeroDwell; }
  else if (ship.throttle === 0 && c.thr < 0) {
    ship.zeroHold -= dt;
    if (ship.zeroHold > 0) thr = 0;
  } else if (c.thr >= 0) ship.zeroHold = 0;
  ship.throttle = clamp(thr, -1, 1);

  // Оглушение после удара: управления нет, вращение просто затухает —
  // корабль кувыркается по инерции.
  const stunned = ship.stun > 0;
  if (stunned) ship.stun = Math.max(0, ship.stun - dt);

  const r = ship.rot;
  const q = ship.rcs;
  if (stunned) {
    const k = Math.max(0, 1 - SHIP.tumbleDamp * dt);
    r.pitch *= k; r.yaw *= k; r.roll *= k;
    q.pitch = q.yaw = q.roll = 0;       // управления нет — и сопла молчат
  } else {
    // Постоянный момент: угловая скорость набирается и гасится ровно,
    // без рывка в первый кадр (см. rotRamp).
    const wp = c.pitch * SHIP.pitchRate, wy = c.yaw * SHIP.yawRate, wr = c.roll * SHIP.rollRate;
    q.pitch = torqueDir(r.pitch, wp, SHIP.pitchAccel * dt);
    q.yaw = torqueDir(r.yaw, wy, SHIP.yawAccel * dt);
    q.roll = torqueDir(r.roll, wr, SHIP.rollAccel * dt);
    r.pitch = rampTo(r.pitch, wp, SHIP.pitchAccel * dt);
    r.yaw = rampTo(r.yaw, wy, SHIP.yawAccel * dt);
    r.roll = rampTo(r.roll, wr, SHIP.rollAccel * dt);
  }
  rotateBasis(ship.basis, r.pitch * dt, r.yaw * dt, r.roll * dt);

  // Оглушённый корабль — просто тело в поле тяжести: ни тяги, ни
  // стабилизации. Именно здесь живёт отскок.
  if (stunned) {
    if (field) {
      ship.vel.x -= field.up.x * field.g * dt;
      ship.vel.y -= field.up.y * field.g * dt;
      ship.vel.z -= field.up.z * field.g * dt;
    }
    ship.speed = Math.hypot(ship.vel.x, ship.vel.y, ship.vel.z);
    ship.pos.x += ship.vel.x * dt;
    ship.pos.y += ship.vel.y * dt;
    ship.pos.z += ship.vel.z * dt;
    return;
  }

  // --- Двигатели, тяготение и гашение заноса.
  //
  // Никакой «заданной скорости» тут больше нет: есть ускорения, и они
  // складываются. Аркадного в модели остаётся одно — маневровые движки
  // гасят снос поперёк носа, иначе каждый разворот пришлось бы
  // отрабатывать вручную, как в орбитальном симуляторе.
  //
  // ШАССИ НЕ МЕНЯЕТ УПРАВЛЕНИЕ. Оно меняет одно — предел скорости.
  //
  // Раньше его выпуск переключал модель полёта целиком: выключался
  // компенсатор высоты (корабль начинал проваливаться сам), а главные
  // движки переставали толкать вверх и работали только по горизонту.
  // Задумано это было как «почувствовать вес на посадке», а на деле
  // читалось как поломка: одна клавиша — и корабль перестаёт слушаться
  // так, как слушался секунду назад. Ни один аппарат от выпуска стоек
  // так себя не ведёт.
  //
  // Теперь компенсатор высоты работает ВСЕГДА: движки держат корабль
  // против местной тяжести, и с нулевой ручкой он висит на месте на
  // любой высоте и с любым шасси. Тяжесть от этого не исчезает — она
  // по-прежнему задаёт силу подъёмных движков (SHIP.liftTWR), решает
  // исход удара и работает в полную силу, пока корабль оглушён (см.
  // выше: там нет ни тяги, ни стабилизации).
  const f = ship.basis.fwd, u = ship.basis.up;
  const gearOut = !!(ship.gear && ship.gear.t > 0.02);
  const up = field ? field.up : null;
  const g = field ? field.g : 0;

  // Ось подъёмных движков — «верх» самого корабля, то есть ровно то,
  // куда они толкают.
  const la = u;
  // Вертикаль считается отдельным каналом, пока отклонена ручка
  // подъёмных движков. Иначе их тяга бессмысленна: гашение заноса ниже
  // видит набранную вертикальную скорость как снос и стирает её в
  // следующем же кадре (0.5 км/с² против 0.004), и R/F не делают ровно
  // ничего.
  const liftOn = c.lift !== 0;
  let vUp = 0;
  if (liftOn) {
    vUp = ship.vel.x * la.x + ship.vel.y * la.y + ship.vel.z * la.z;
    ship.vel.x -= la.x * vUp; ship.vel.y -= la.y * vUp; ship.vel.z -= la.z * vUp;
  }

  // Направление тяги — всегда нос, независимо от шасси.
  const fx = f.x, fy = f.y, fz = f.z;

  // Главные движки: разгон до скорости, заданной тягой. С выпущенным
  // шасси предел ниже — на нём не летают.
  const lim = SHIP.maxSpeed * (gearOut ? SHIP.gearSpeed : 1) * boost;
  const target = ship.throttle * lim * (ship.throttle < 0 ? SHIP.reverse : 1);
  const cur = ship.vel.x * fx + ship.vel.y * fy + ship.vel.z * fz;
  const aBoost = ship.boosting ? SHIP.boostAccel : 1;
  const aLim = (Math.abs(target) > Math.abs(cur) ? SHIP.accel * aBoost : SHIP.brake) * dt;
  const step = clamp(target - cur, -aLim, aLim);
  ship.vel.x += fx * step;
  ship.vel.y += fy * step;
  ship.vel.z += fz * step;

  // Гашение заноса: всё, что не вдоль тяги.
  const dot0 = ship.vel.x * fx + ship.vel.y * fy + ship.vel.z * fz;
  const px = ship.vel.x - fx * dot0, py = ship.vel.y - fy * dot0, pz = ship.vel.z - fz * dot0;
  const perp = Math.hypot(px, py, pz);
  if (perp > 1e-9) {
    const k = Math.min(1, SHIP.lateral * dt / perp);
    ship.vel.x -= px * k;
    ship.vel.y -= py * k;
    ship.vel.z -= pz * k;
  }

  // Подъёмные движки: ТЯГА, а не скорость. Сила привязана к местной
  // тяжести (SHIP.liftTWR), вдали от тел — постоянная.
  const liftAcc = Math.max(SHIP.liftMin, g * SHIP.liftTWR) * c.lift;
  ship.lift = liftAcc;

  if (liftOn) {
    // Вес в точности гасит компенсатор высоты, и движки разгоняют
    // корабль вдоль «верха» — вертикальная скорость КОПИТСЯ, пока ручка
    // отклонена. Отпустил — канал снова общий, и стабилизатор гасит
    // набранное так же, как любой другой снос.
    vUp += liftAcc * dt;
    ship.vel.x += la.x * vUp; ship.vel.y += la.y * vUp; ship.vel.z += la.z * vUp;
  }

  ship.speed = Math.hypot(ship.vel.x, ship.vel.y, ship.vel.z);
  if (ship.speed < 1e-5) {
    ship.vel.x = ship.vel.y = ship.vel.z = 0;
    ship.speed = 0;
  }

  ship.pos.x += ship.vel.x * dt;
  ship.pos.y += ship.vel.y * dt;
  ship.pos.z += ship.vel.z * dt;
}

// Мгновенно поставить корабль в точку с заданной ориентацией.
export function placeShip(ship, pos, basis) {
  copy(ship.pos, pos);
  if (basis) {
    copy(ship.basis.right, basis.right);
    copy(ship.basis.up, basis.up);
    copy(ship.basis.fwd, basis.fwd);
  }
  ship.speed = 0;
  ship.vel.x = ship.vel.y = ship.vel.z = 0;
  ship.throttle = 0;
  ship.boostPunch = 0;
  ship.boostLock = false;
  ship.zeroHold = 0;
  ship.stun = 0;
  ship.lift = 0;
  ship.rot.pitch = ship.rot.yaw = ship.rot.roll = 0;
}
