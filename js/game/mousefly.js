// Управление мышью (Ctrl+Пробел): виртуальная ручка, как в Star Citizen.
//
// Мышь не «тянет нос» напрямую, а двигает невидимую ручку: её отклонение
// от центра — это СКОРОСТЬ поворота носа, как у настоящей ручки. Сдвинул
// мышь вправо — корабль поворачивает вправо и будет поворачивать, пока
// ручку не вернут к середине. Прямое «мышь = угол носа» у корабля с
// инерцией не работает: нос не успевает за рукой, и пилот перекручивает.
//
// В середине мёртвая зона: рука на мыши никогда не стоит идеально, и без
// неё корабль вечно чуть-чуть плыл бы. За ней отклонение растёт плавнее
// линейного (кривая): мелкая поправка прицела — малым ходом, разворот —
// большим.
//
// Нос в этом режиме ведёт только ручка: W/S/A/D его не трогают
// (js/game/ship.js, readControls). Крен, тяга, подъёмные, форсаж и всё
// прочее — клавишами, как прежде. Модуль ничего не знает про ввод и
// кадр — только числа, и проверяется в Node (tools/test.mjs).

export const STICK = {
  // Сколько пикселей хода мыши от центра до полного отклонения. Триста —
  // это полковрика: разворот на полной скорости не требует отрывать руку.
  px: 300,
  // Мёртвая зона — доля полного хода.
  dead: 0.06,
  // Степень кривой за мёртвой зоной: 1 — линейно.
  curve: 1.6,
  // Радиус кольца ручки в приборах, пикселей экрана.
  ring: 90,
};

export const makeStick = () => ({ on: false, x: 0, y: 0, locked: false });

/** Сдвиг мыши (пиксели) — в ход ручки; за кольцо она не выходит. */
export function moveStick(s, dx, dy) {
  s.x += dx / STICK.px;
  s.y += dy / STICK.px;
  const l = Math.hypot(s.x, s.y);
  if (l > 1) { s.x /= l; s.y /= l; }
  return s;
}

export function centerStick(s) {
  s.x = 0;
  s.y = 0;
  return s;
}

/**
 * Ручка — в органы управления: рыскание и тангаж от -1 до 1. Мёртвая
 * зона и кривая — по ДЛИНЕ отклонения, а не по осям порознь: иначе
 * наискосок нос шёл бы ступеньками, сначала по одной оси, потом по другой.
 *
 * Тангаж — как у клавиш: S (+1) задирает нос, W (-1) опускает. Мышь
 * вверх по экрану задирает нос: на экране «вверх» — это «туда смотреть»
 * (без инверсии, как у Star Citizen по умолчанию).
 */
export function stickControls(s, out = { pitch: 0, yaw: 0 }) {
  const r = Math.hypot(s.x, s.y);
  if (r <= STICK.dead) {
    out.pitch = 0;
    out.yaw = 0;
    return out;
  }
  const k = ((Math.min(r, 1) - STICK.dead) / (1 - STICK.dead)) ** STICK.curve / r;
  out.yaw = s.x * k;
  out.pitch = -s.y * k;
  return out;
}
