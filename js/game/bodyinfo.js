/** Давление у поверхности, бар. Ноль означает «воздуха нет». */
export const pressureOf = (kind) => (KIND_INFO[kind] ? KIND_INFO[kind].press : 0);

/** Масса тела, кг: та же плотность, по которой считается гравитация. */
export function massOf(body) {
  const rho = DENSITY[body.kind] || DENSITY.rock;      // кг/м³
  const r = body.radius * 1000;                        // м
  return rho * (4 / 3) * Math.PI * r * r * r;
}

/** Вторая космическая, км/с: sqrt(2μ/R). */
export const escapeSpeed = (body) => Math.sqrt(2 * body.mu / body.radius);

/** Длительность суток, с. */
export const dayLength = (body) => (body.spin ? TAU / body.spin : Infinity);

/**
 * Атмосфера тела или null.
 * Верх берётся из той же константы, по которой считается нагрев при
 * входе, — иначе панель обещала бы воздух там, где его уже нет.
 */
export function atmosphereOf(body) {
  if (!body || !body.atmo) return null;
  const info = KIND_INFO[body.kind] || {};
  return {
    press: info.press || 1,
    top: body.radius * ENTRY.top,
    mix: info.mix || null,
  };
}

// Равновесная температура на орбите родной планеты, К. Земные 255 К:
// вместе с парниковыми +33 они дают привычные +15 °C у поверхности.
//
// Считать светимость честно, из радиуса и температуры светила, тут
// нельзя: орбиты в системе сжаты до 0.3–3.6 млн км (см. README), и
// настоящая формула дала бы у обитаемой планеты полторы тысячи
// градусов. Поэтому шкала привязана к родному миру, а дальше работает
// настоящий закон: поток падает как квадрат расстояния, температура —
// как корень из него.
export const T_EQ_HOME = 255;

/** Расстояние тела до светила, км (у лун и станций — расстояние хозяина). */
export function starDistance(body) {
  for (let node = body; node; node = node.parent) {
    if (node.parent && !node.parent.parent && node.orbit) return node.orbit.radius;
  }
  return body.orbit ? body.orbit.radius : 0;
}

/**
 * Температура у поверхности, К.
 * @param world нужен ради калибровки по родной планете
 */
export function temperatureOf(world, body) {
  const info = KIND_INFO[body.kind] || KIND_INFO.rock;
  // У светила температура своя, и она из КЛАССА звезды: в таблице видов
  // она одна на все звёзды, а классов пять (js/game/galaxy.js).
  if (info.temp) return body.temp || info.temp;
  const d = starDistance(body);
  // Опора — обитаемая зона системы, а не родная планета. Зона считается
  // из светимости звезды, поэтому у красного карлика та же 255 K
  // приходится на 150 тыс. км, а у белой — на полтора миллиона. Пока
  // опорой была планета (world.home), в чужой системе это значило бы
  // «где-то там обязана быть планета с земным климатом».
  const d0 = world.habitable || (world.home && world.home.orbit.radius) || 620000;
  const a0 = KIND_INFO.ocean.albedo;
  if (!(d > 0)) return info.temp || 0;
  // T ~ d^(-1/2), поправка на альбедо — корень четвёртой степени из
  // поглощённой доли: обе части закона Стефана-Больцмана.
  const eq = T_EQ_HOME * Math.sqrt(d0 / d) * ((1 - info.albedo) / (1 - a0)) ** 0.25;
  return eq + info.heat;
}

export const toCelsius = (k) => k - 273.15;

/** Тип объекта одним словом — им подписан заголовок карточки. */
export function kindLabel(obj) {
  if (!obj) return '—';
  if (obj.isStation) return L('орбитальная станция');
  if (obj.isMarker) return L('орбитальный маркер');
  const info = KIND_INFO[obj.kind];
  // Названия типов лежат в таблице по-русски и переводятся ЗДЕСЬ, на
  // выходе: таблица — это каталог мира, а не надписи прибора, и держать
  // в ней два языка значит завести второй каталог.
  return info ? L(info.ru) : obj.kind;
}
