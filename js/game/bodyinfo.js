// Справка об объекте: что карта системы пишет о планете, луне, станции
// или орбитальном маркере.
//
// Модуль намеренно отдаёт ЧИСЛА, а не готовые строки: форматированием
// занимается карта (js/ui/map.js), а проверить «сколько тут тяжесть и
// откуда она взялась» можно в node, не рисуя ни пикселя.
//
// Главное правило то же, что и везде: в карточке нет ни одного числа,
// придуманного отдельно от мира. Масса считается из плотности и радиуса
// (те же DENSITY, по которым работает гравитация), тяжесть и вторая
// космическая — из массы, сутки — из периода вращения, год — из орбиты,
// высота атмосферы — из той же константы, по которой считается нагрев
// при входе. Иначе панель рассказывала бы про одну планету, а летал бы
// корабль над другой.
//
// Таблицей задано ровно то, что из модели не выводится: словесное
// описание, состав воздуха, давление у поверхности, альбедо и
// собственный нагрев тела. Это справочные величины настоящих аналогов
// (Земля, Марс, Титан, Юпитер, Ио), а не подобранные на глаз.

