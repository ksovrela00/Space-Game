// Вход в атмосферу: плотность воздуха, нагрев обшивки и его вид.
//
// Считается отдельно от рендера и без единого обращения к GL: рендеру
// отсюда уходят три числа — сила свечения, его цвет и ось, вдоль которой
// строится ударная волна. Поэтому нагрев можно проверить в node, а не
// «посмотреть глазами и вроде похоже».
//
// Физики ровно столько, чтобы поведение было предсказуемым:
//
//   * плотность падает по экспоненте с высотой (барометрическая
//     формула). Верх атмосферы взят там же, где её рисует сцена, —
//     иначе пламя начиналось бы там, где воздуха ещё не видно;
//   * тепловой поток растёт как sqrt(ρ)·v³ — это формула Саттона-Грейвза
//     для лобовой точки. Куб скорости здесь главное: он и означает, что
//     «краснота зависит от скорости входа», причём резко. Вдвое быстрее
//     вошёл — в восемь раз горячее;
//   * скорость берётся ОТНОСИТЕЛЬНО воздуха, и это та же скорость, по
//     которой проверяется посадка (groundDrift в js/game/gravity.js).
//     Важно не перепутать её с орбитальной: внутри захвата корабль уже
//     переносится вместе с телом, и вычитать скорость тела ещё раз
//     значит поджигать всех, кто просто висит над планетой.
//
// Пороги (vFloor, vFull) стоят по обычному полёту: на полном ходу
// корабль входит с заметным свечением, на форсаже — горит целиком.
// Квантовый привод сюда не приходит вовсе: в прыжке нет ни атмосферы,
// ни столкновений, он проверяет коридор заранее.

import { clamp } from '../core/vec3.js';
import { groundDrift } from './gravity.js';

export const ENTRY = {
  // Верх атмосферы в долях радиуса тела. Столько же берёт оболочка
  // атмосферы в сцене (radius * 1.035).
  top: 0.035,
  // Сколько шкал высоты укладывается до верха: на самом верху остаётся
  // e^-5, меньше процента — там уже вакуум.
  scales: 5,
  // Порог и насыщение по скорости обдува, км/с. Ниже порога нагрева нет
  // вовсе: снижаться на планету можно и нужно без фейерверка. Порог
  // взят выше скорости вращения планет (у них это 100-250 м/с), иначе
  // висящий над грунтом корабль светился бы от одного лишь ветра.
  vFloor: 0.32,
  vFull: 1.4,
  // Где свечение белое, а где уже красное (км/с). На околозвуковых
  // скоростях в плотном воздухе вокруг корабля стоит белый конус
  // уплотнения, а раскалённая плазма приходит позже и она оранжево-
  // красная — как на снимках возвращаемых аппаратов. Поэтому по цвету
  // читается не «горячее/холоднее», а КАК БЫСТРО идёшь.
  vWhite: 0.45,
  vRed: 1.25,
  // Ниже этого свечение не рисуем: экономия и отсутствие мерцающей
  // точки на горизонте.
  minHeat: 0.02,
};

/**
 * Плотность воздуха на высоте, 0..1 (единица — у поверхности).
 * @param alt высота над сферой тела, км
 */
export function airDensity(body, alt) {
  if (!body || !body.atmo) return 0;
  const top = body.radius * ENTRY.top;
  if (alt >= top) return 0;
  if (alt <= 0) return 1;
  return Math.exp(-ENTRY.scales * (alt / top));
}

/**
 * Нагрев 0..1 по плотности и скорости обдува.
 * @param speed скорость относительно воздуха, км/с
 */
export function entryHeat(rho, speed) {
  if (rho <= 0) return 0;
  const v = clamp((speed - ENTRY.vFloor) / (ENTRY.vFull - ENTRY.vFloor), 0, 1);
  if (v <= 0) return 0;
  return clamp(Math.sqrt(rho) * v * v * v, 0, 1);
}

/**
 * Цвет свечения по СКОРОСТИ обдува: белый на околозвуковых, красный на
 * гиперзвуке.
 *
 * Цвет отвязан от силы свечения намеренно. Сила говорит, сколько энергии
 * уходит в обшивку (её задаёт плотность), а цвет — насколько быстро
 * идёшь. Иначе густой воздух на малой скорости и разреженный на большой
 * выглядели бы одинаково, хотя это разные вещи: в первом случае вокруг
 * корабля белый конус уплотнения, во втором — красная плазма.
 *
 * @param speed скорость обдува, км/с
 */
export function heatColor(speed, out = [0, 0, 0]) {
  const t = clamp((speed - ENTRY.vWhite) / (ENTRY.vRed - ENTRY.vWhite), 0, 1);
  // Белый -> жёлто-оранжевый -> красный. Красный канал держится всегда:
  // свечение любой скорости остаётся тёплым.
  out[0] = 1;
  // Синий уходит раньше зелёного: иначе середина шкалы получается
  // розовой, а должна быть янтарной.
  out[1] = 0.97 - 0.70 * t;
  out[2] = 0.92 - 0.90 * Math.pow(t, 0.6);
  return out;
}

const _rel = { x: 0, y: 0, z: 0 };
const _air = { x: 0, y: 0, z: 0 };

/**
 * Обстановка входа для корабля: ближайшее тело с воздухом, плотность,
 * скорость обдува, нагрев и ось ударной волны.
 *
 * @returns null вне атмосферы, иначе {body, alt, rho, speed, heat, dir}
 */
export function entryState(world, ship, out = null) {
  let best = null, bestAlt = Infinity;
  for (const b of world.bodies) {
    if (!b.atmo) continue;
    const d = Math.hypot(ship.pos.x - b.pos.x, ship.pos.y - b.pos.y, ship.pos.z - b.pos.z);
    const alt = d - b.radius;
    if (alt >= b.radius * ENTRY.top) continue;
    if (alt < bestAlt) { bestAlt = alt; best = b; }
  }
  if (!best) return null;

  const rho = airDensity(best, bestAlt);
  // Воздух едет вместе с телом. Берём тот же снос, что у грунта при
  // посадке: внутри захвата орбитальная скорость уже учтена переносом
  // системы отсчёта, остаётся только вращение.
  groundDrift(best, ship.pos, _air);
  _rel.x = ship.vel.x - _air.x;
  _rel.y = ship.vel.y - _air.y;
  _rel.z = ship.vel.z - _air.z;
  const speed = Math.hypot(_rel.x, _rel.y, _rel.z);
  const heat = entryHeat(rho, speed);
  if (heat < ENTRY.minHeat) return null;

  const res = out || { dir: { x: 0, y: 0, z: 0 }, color: [0, 0, 0] };
  res.body = best;
  res.alt = bestAlt;
  res.rho = rho;
  res.speed = speed;
  res.heat = heat;
  // Ось факела — куда корабль летит, а не куда смотрит носом: горит
  // набегающий поток, и ему всё равно, как повёрнут корабль.
  const inv = speed > 1e-9 ? 1 / speed : 0;
  res.dir.x = _rel.x * inv; res.dir.y = _rel.y * inv; res.dir.z = _rel.z * inv;
  heatColor(speed, res.color);
  return res;
}
