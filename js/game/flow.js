// Пылинки за бортом: то, чем в пустоте видно скорость.
//
// Зачем. В космосе скорость не видно ничем. Звёзды бесконечно далеко и
// стоять на месте — их законное поведение (js/gl/scene.js, drawStars),
// до планеты миллион километров, и корабль на полном ходу выглядит
// ровно так же, как корабль на месте. Форсаж, ради которого всё
// затевалось, при этом читается только по цифре на приборе.
//
// Отсюда пылинки — крошка и лёд, которые проносятся мимо у самого
// борта. Условность здесь ровно одна, и её стоит назвать вслух:
// НАСТОЯЩАЯ межпланетная пыль так редка, что мимо не пролетело бы
// ничего за всю партию. Плотность потока выдумана. Всё остальное
// следует из движения корабля, а не из флага «включить эффект»:
//
//   * пылинки стоят на месте, а мимо идёт КОРАБЛЬ. Поэтому здесь
//     копится не «фаза эффекта», а пройденный путь — и поток сам собой
//     разворачивается по вектору скорости, тормозит вместе с кораблём
//     и замирает, когда тот встал;
//   * путь берётся от СОБСТВЕННОЙ скорости, а не от смещения в мире.
//     В гравитационном захвате корабль переносится вместе с планетой
//     (js/game/gravity.js) и за секунду проходит по орбите десятки
//     километров — если считать по миру, над неподвижной точкой грунта
//     мимо неслась бы метель;
//   * черта — это смаз: за время экспозиции пылинка сместилась
//     относительно корабля на v·smear, и хвост линии стоит там, где она
//     была. На форсаже предел скорости втрое выше — черта втрое
//     длиннее, сама собой, безо всякого «режима полос».
//
// Яркость — единственное, что здесь подача, а не физика: по-честному
// быстрая пылинка размазывает тот же свет по большей длине и должна
// ТУСКНЕТЬ. Но просили обратного, и повод есть: привязываем яркость к
// тому, насколько корабль перевалил за обычный предел скорости, а
// перевалить за него можно только форсажем. Без форсажа поток остаётся
// еле заметной рябью, с ним — стеной полос.
//
// Путь копится здесь, в шаге игрока, а не в кадре рендера: картинка не
// должна зависеть от частоты кадров. Рендер отсюда только читает.

import { SHIP } from './ship.js';

export const FLOW = {
  // Шаг решётки: в кубе такого размера вокруг корабля стоит ровно
  // столько пылинок, сколько их в мешe (js/gl/scene.js, MOTE_COUNT).
  // Два километра при четырёх сотнях пылинок — это одна крошка на
  // каждые триста метров: в кадре десятки черт, а не метель.
  box: 2.0,           // км
  // Время «экспозиции»: за него пылинка смазывается в черту. Восемь
  // сотых — это и выдержка глаза на тусклом предмете, и заодно то, при
  // чём на обычном ходу получается короткий штрих, а на форсаже —
  // длинная полоса.
  smear: 0.08,        // с
  // Предел длины черты. Дальше хвост уходит за край ячейки, и поток
  // превращается в сетку из сплошных линий.
  streakMax: 0.7,     // км
  // Яркость: на обычном пределе скорости и на полном форсаже.
  calm: 0.10,
  burn: 1,
};

export function makeFlow() {
  return {
    // Пройденный путь в долях ячейки, [0..1) по каждой оси. Держим его
    // свёрнутым: за час полёта километры сложились бы в число, в
    // котором float32 уже не различает метры.
    ofs: { x: 0, y: 0, z: 0 },
    // Смаз за экспозицию, км — вектор: рендеру он нужен целиком.
    streak: { x: 0, y: 0, z: 0 },
    power: 0,
    speed: 0,
  };
}

/**
 * Пересчитать поток.
 *
 * @param flow состояние (makeFlow)
 * @param game нужны ship и quantum
 * @param dt   шаг по времени игрока
 */
export function updateFlow(flow, game, dt) {
  const ship = game.ship;
  const q = game.quantum;
  flow.power = 0; flow.speed = 0;
  flow.streak.x = 0; flow.streak.y = 0; flow.streak.z = 0;
  if (!ship || ship.dockedAt) return flow;
  // В самом прыжке поток свой — куда гуще и быстрее этого
  // (js/gl/scene.js, updateJump). Два потока в одном кадре — каша.
  if (q && q.phase === 'jump') return flow;

  const v = ship.vel;
  const sp = Math.hypot(v.x, v.y, v.z);
  flow.speed = sp;
  if (!(sp > 1e-9)) return flow;

  // Быстрее форсажного предела корабль идёт только на рельсах привода —
  // например, гасит ход после срыва прыжка. Там скорость измеряется
  // десятками тысяч км/с: за кадр решётка проскочила бы сотни ячеек, и
  // вместо потока получилась бы случайная рябь. Поэтому картинка
  // упирается в предел КОРАБЛЯ, а не в его скорость.
  const top = SHIP.maxSpeed * SHIP.boostMax;
  const use = Math.min(sp, top);

  // Решётка сдвигается на пройденный путь и тут же сворачивается в
  // ячейку: дальше рендеру нужна только дробная часть.
  const step = dt * use;
  flow.ofs.x = wrap(flow.ofs.x + (v.x / sp) * step / FLOW.box);
  flow.ofs.y = wrap(flow.ofs.y + (v.y / sp) * step / FLOW.box);
  flow.ofs.z = wrap(flow.ofs.z + (v.z / sp) * step / FLOW.box);

  // Смаз: где пылинка была экспозицию назад — относительно корабля она
  // ушла назад по курсу ровно на столько.
  const len = Math.min(FLOW.streakMax, use * FLOW.smear);
  flow.streak.x = (v.x / sp) * len;
  flow.streak.y = (v.y / sp) * len;
  flow.streak.z = (v.z / sp) * len;

  // Насколько корабль перевалил за обычный предел: 0 — не перевалил
  // вовсе, 1 — идёт на полном форсаже.
  const over = Math.min(1, Math.max(0, (use / SHIP.maxSpeed - 1) / (SHIP.boostMax - 1)));
  const soft = Math.min(1, use / SHIP.maxSpeed);
  flow.power = FLOW.calm * soft + (FLOW.burn - FLOW.calm) * over * over;
  return flow;
}

const wrap = (x) => x - Math.floor(x);
