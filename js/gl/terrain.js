const rampAt = (ramp, t, out) => {
  let a = ramp[0], b = ramp[ramp.length - 1];
  for (let i = 1; i < ramp.length; i++) {
    if (ramp[i][0] >= t) { a = ramp[i - 1]; b = ramp[i]; break; }
  }
  const span = (b[0] - a[0]) || 1;
  const k = clamp01((t - a[0]) / span);
  out[0] = (a[1][0] + (b[1][0] - a[1][0]) * k) / 255;
  out[1] = (a[1][1] + (b[1][1] - a[1][1]) * k) / 255;
  out[2] = (a[1][2] + (b[1][2] - a[1][2]) * k) / 255;
  return out;
};

/**
 * Поверхность конкретного тела.
 *
 * detail — объект из detailForCell(): сколько октав шума и сколько
 * масштабов кратеров считать. По умолчанию берётся полная детализация:
 * её использует игровая логика (высота поверхности под кораблём), а
 * сетки рендера просят ровно столько, сколько способны показать.
 */
// --- Ровная площадка под наземным городом --------------------------------------
//
// Город стоит не на подставке: площадка — это САМА ПОВЕРХНОСТЬ. По ней
// считаются и высота под кораблём, и посадка, и столкновение, и сетка,
// которую рисует видеокарта, — иначе нарисованное и настоящее разошлись
// бы, а посадочная площадка оказалась бы на склоне кратерного вала
// (js/game/city.js).
//
// Вес считается по КВАДРАТУ ХОРДЫ между направлениями, а не по углу:
// рельеф выбирают миллионы раз за кадр, и арккосинус в этом месте стоил
// бы дороже самого рельефа. Квадрат хорды монотонен по углу и даётся
// тремя умножениями.

/** Бетон площадки. Светлее грунта — это видно и с орбиты. */
export const PLATE_RGB = [0.42, 0.435, 0.455];

/**
 * Излом края плиты: во сколько раз её радиус в этом направлении больше
 * или меньше среднего. Три гармоники по углу вокруг местной вертикали.
 *
 * Возвращается КВАДРАТ множителя: сравнивают всё равно квадраты хорд, а
 * радиус в квадрате — это множитель в квадрате. Арктангенса здесь нет и
 * быть не может: косинусы кратных углов считаются из косинуса и синуса
 * первого тремя умножениями каждый, а atan2 в функции, которую зовут
 * миллионы раз за кадр, стоил бы дороже всего рельефа.
 *
 * Слово в слово повторено в шейдере — js/gl/detail.js, dPlate().
 */
function plateWobble(p, dx, dy, dz) {
  const u = dx * p.ax + dy * p.ay + dz * p.az;
  const v = dx * p.bx + dy * p.by + dz * p.bz;
  const r = Math.sqrt(u * u + v * v);
  if (r < 1e-12) return 1;
  const c = u / r, si = v / r;
  const c2 = c * c - si * si, s2 = 2 * c * si;
  const c3 = c2 * c - s2 * si, s3 = s2 * c + c2 * si;
  const f = 1 + p.k1c * c + p.k1s * si + p.k2c * c2 + p.k2s * s2 + p.k3c * c3 + p.k3s * s3;
  return f * f;
}

/** Вес площадки в точке: 1 на плите, 0 за краем перехода. */
export function plateAt(plate, x, y, z) {
  const dx = x - plate.x, dy = y - plate.y, dz = z - plate.z;
  const d2 = dx * dx + dy * dy + dz * dz;
  if (d2 >= plate.dMax) return 0;
  const w2 = plateWobble(plate, dx, dy, dz);
  const d0 = plate.d0 * w2, d1 = plate.d1 * w2;
  if (d2 >= d1) return 0;
  if (d2 <= d0) return 1;
  return 1 - smooth01((d2 - d0) / (d1 - d0));
}

/**
 * Доля бетона в цвете грунта.
 *
 * Отдельно от выравнивания, и вот почему: ровной обязана быть вся
 * плита — под городом в семьдесят километров иначе не построить, — а
 * СЕРОЙ она быть не обязана. Сплошной бетонный круг такого размера
 * выглядит не городом, а карьером. Поэтому тонируется ядро, а дальше
 * остаётся просто выровненный грунт своего цвета.
 */
export function plateTint(plate, x, y, z) {
  const dx = x - plate.x, dy = y - plate.y, dz = z - plate.z;
  const d2 = dx * dx + dy * dy + dz * dz;
  if (d2 >= plate.dMax) return 0;
  const w2 = plateWobble(plate, dx, dy, dz);
  const t0 = plate.t0 * w2, t1 = plate.t1 * w2;
  if (d2 <= t0) return 1;
  if (d2 >= t1) return 0;
  return 1 - smooth01((d2 - t0) / (t1 - t0));
}

export const terrainOf = (body) => body._terrain || (body._terrain = makeTerrain(body));

export function makeTerrain(body) {
  const cfg = KIND[body.kind] || KIND.rock;
  const seed = (strHash(body.name + '#' + body.id) ^ 0x5a7e) | 0;
  const ramp = RAMP[body.kind] || RAMP.rock;
  const isGas = body.kind === 'gas';
  const craterW = cfg.craters;
  const mnt = isGas ? null : (cfg.mount || null);
  // Высота горы в полную силу — по ней нормируется подкраска (MOUNT_TINT).
  const mountMax = mnt ? mnt.amp * (MOUNT_K * MOUNT_TAIL + MOUNT_B) : 1;

  // Сколько октав и масштабов кратеров имеет смысл считать для сетки с
  // угловым размером ячейки cellRad. Порог 2.5 ячейки на период — ниже
  // него деталь не представима и превращается в шум.
  const detailForCell = (cellRad) => {
    const lim = Math.max(1e-9, 2.5 * cellRad);
    let oct = 1 + Math.floor(Math.log(1 / (cfg.freq * lim)) / Math.log(LAC));
    if (!isFinite(oct) || oct < 1) oct = 1;
    if (oct > 26) oct = 26;
    let cs = 0;
    if (craterW > 0) {
      while (cs < CRATER_MAX_SCALES && CRATER_C0 * CRATER_STEP ** cs >= lim) cs++;
    }
    // Октавы горного слоя считаются по его СОБСТВЕННОЙ частоте, и она в
    // сотню раз выше основной. Поэтому на грубой сетке их выходит ноль:
    // гор в геометрии нет вовсе, их добавляет шейдер, — а по мере
    // дробления сетка забирает их себе, октаву за октавой. Ровно та же
    // лестница, что у кратеров, и ровно так же за неё отвечает
    // detailGap.
    let moct = 0;
    if (mnt) {
      moct = 1 + Math.floor(Math.log(1 / (mnt.freq * lim)) / Math.log(LAC));
      if (!isFinite(moct) || moct < 0) moct = 0;
      if (moct > MOUNT_MAX_OCT) moct = MOUNT_MAX_OCT;
    }
    return { oct, cs, moct, cellRad };
  };
  const FULL = detailForCell(1e-7);

  // Сырая высота в [-1, 1] до вычета уровня моря.
  const raw = (x, y, z, oct) => (cfg.ridge
    ? ridged(seed, x, y, z, oct, cfg.freq)
    : fbm(seed, x, y, z, oct, cfg.freq));

  /**
   * Плотность кратеров: 0 в «морях», 1 на «материках».
   *
   * Без этой маски кратеры равномерно покрывают весь шар, и поверхность
   * выглядит пузырчатой плёнкой. У настоящих безатмосферных тел
   * кратерами насыщены древние высокогорья, а залитые лавой низины
   * почти гладкие — именно этот контраст и читается как «луна».
   *
   * Частота низкая (пятна в тысячи километров), поэтому сетка передаёт
   * маску вершинами без потерь, а шейдер считает её один раз на пиксель.
   */
  const mare = (x, y, z) =>
    smooth01((fbm(seed + 991, x * 1.3, y * 1.3, z * 1.3, 3, 1) + 0.25) / 0.5);

  /**
   * Пояс гор: 0 на равнине, 1 в горах.
   *
   * Три октавы низкой частоты — как у маски «морей». Считать её
   * подробнее нечем и незачем: пояс размером в тысячи километров сетка
   * передаёт вершинами без потерь, а шейдеру он стоит три вызова шума
   * и позволяет пропустить весь горный цикл на равнине.
   */
  const belt = !mnt ? () => 0 : (x, y, z) => {
    const n = fbm(seed + MOUNT_SEED + 17,
      x * mnt.spread, y * mnt.spread, z * mnt.spread, 3, 1);
    return smooth01((n - mnt.thr) / mnt.soft);
  };

  /**
   * Высота гор над базовым рельефом, доли радиуса.
   *
   * @param moct сколько октав хребтов считать (из detailForCell)
   */
  const mountains = !mnt ? () => 0 : (x, y, z, moct, r) => {
    if (moct <= 0) return 0;
    // Только на суше и плавно от берега (см. MOUNT_RISE).
    const land = smooth01((r - cfg.sea) / MOUNT_RISE);
    if (land <= 0) return 0;
    const w = belt(x, y, z);
    if (w <= 0) return 0;
    const t = MOUNT_K * ridged(seed + MOUNT_SEED, x, y, z, moct, mnt.freq) + MOUNT_B;
    return mnt.amp * w * land * t;
  };

  // Газовый гигант: полосы по широте плюс лёгкая турбулентность.
  const gasBand = (x, y, z) => {
    const swirl = fbm(seed + 31, x * 0.6, y * 3.0, z * 0.6, 4, 1.2) * 0.12;
    const lat = y + swirl;
    return Math.sin(lat * 7.5) * 0.5 + fbm(seed + 77, x, y * 2.2, z, 3, 1.6) * 0.25;
  };

  // Высота над уровнем моря нормируется на этот размах: ноль на уровне
  // моря, единица на максимуме шума.
  const span = 1 - cfg.sea;

  const flat = isGas || cfg.amp === 0;

  // Нормированная высота для цветовой рампы по уже посчитанному шуму.
  const normOf = (r) => {
    if (!cfg.water) return clamp01((r - cfg.sea) / span);
    // У водных миров нижние 20% рампы отданы глубинам.
    const d = r - cfg.sea;
    if (d <= 0) return Math.max(0, Math.min(0.2, 0.2 + d * 0.6));
    return Math.max(0.21, Math.min(1, 0.21 + (d / span) * 0.9));
  };

  /**
   * Место точки на цветовой рампе: 0 — дно, 1 — снег.
   *
   * Отдельной функцией, потому что по ней решает не только цвет.
   * Растительность (js/gl/flora.js) спрашивает ровно это: расти надо
   * там, где земля ЗЕЛЁНАЯ, а не просто на подходящей высоте. Разница
   * не теоретическая — на горном склоне высота над уровнем моря ещё
   * лесная, а грунт уже каменного цвета, и деревья росли бы на голой
   * скале.
   */
  const rampPos = (x, y, z, r, hm) => {
    let t = normOf(r);
    // Гора идёт по той же рампе, что и высота, но в СВОЁМ масштабе
    // (MOUNT_TINT): зелёное подножие, каменный склон, снежный гребень.
    if (hm > 0) t = clamp01(t + (hm / mountMax) * MOUNT_TINT);
    // Полярные шапки: по широте (y — ось вращения) с рваной кромкой.
    // Над океаном это морской лёд, поэтому высота здесь не важна.
    if (cfg.caps) {
      const lat = Math.abs(y);
      const edge = 0.72 + fbm(seed + 501, x * 3, y * 3, z * 3, 3, 2.0) * 0.10;
      if (lat > edge) t = Math.max(t, 0.96);
    }
    return t;
  };

  /**
   * Высота и цвет в одном проходе: шум и кратеры считаются по разу.
   * Отдельные displace() и color() дороже вдвое, а вершин в подробной
   * сетке — десятки тысяч.
   * @returns смещение поверхности в долях радиуса; цвет пишется в rgb.
   */
  const sample = (x, y, z, detail, rgb) => {
    const d = detail || FULL;
    if (isGas) {
      if (rgb) rampAt(ramp, clamp01(gasBand(x, y, z) * 0.5 + 0.5), rgb);
      return 0;
    }
    const r = flat ? 0 : raw(x, y, z, d.oct);
    const dens = !flat && craterW > 0 ? mare(x, y, z) : 0;
    const cr = craterW > 0 && d.cs > 0
      ? craterW * craterField(seed + CRATER_SEED, x, y, z, d.cs, dens)
      : 0;
    // Горы кладутся ПОВЕРХ базового рельефа и только на сушу. Про воду
    // это не придирка: хребет посреди океана вылез бы из ровной водной
    // сферы отдельно стоящим конусом без берега и без отмели, и океан
    // из-за одного слоя превратился бы в крошево островов — ровно то,
    // от чего слой и отделяли.
    const hm = !mnt || flat ? 0 : mountains(x, y, z, d.moct, r);
    // Ниже уровня моря — ровная водная сфера, а не дно.
    let h = flat ? 0 : clamp01((r - cfg.sea) / span) * cfg.amp + cr + hm;
    // Площадка города: выравнивает и высоту, и цвет. Читается прямо из
    // тела, а не запоминается при сборке рельефа, — тогда порядок
    // «сначала город, потом первая выборка» перестаёт быть условием.
    const pw = body.plate ? plateAt(body.plate, x, y, z) : 0;
    if (pw > 0) h += (body.plate.h - h) * pw;

    if (rgb) {
      const t = rampPos(x, y, z, r, hm);
      rampAt(ramp, t, rgb);
      // Пятнистость, чтобы поверхность не выглядела «пластиковой», плюс
      // подсветка валов и затемнение дна кратеров: без этого кратеры
      // читаются только в скользящем свете.
      let k = 1 + fbm(seed + 909, x * 6, y * 6, z * 6, 3, 2.4) * 0.10;
      if (cr !== 0) k *= 1 + Math.max(-0.30, Math.min(0.30, cr / (cfg.amp * 0.5)));
      // «Моря» темнее высокогорий — это заливший их базальт. Шейдер
      // этого уже не повторяет: маска низкочастотная, и цвет вершин
      // передаёт её без потерь.
      if (craterW > 0) k *= 0.72 + 0.28 * dens;
      rgb[0] = clamp01(rgb[0] * k);
      rgb[1] = clamp01(rgb[1] * k);
      rgb[2] = clamp01(rgb[2] * k);
      if (pw > 0) {
        // Ядро города — бетон, окраина плиты — чуть подсветлённый
        // грунт: по светлому пятну город находят с воздуха раньше, чем
        // различимы дома, и терять эту подсказку нельзя.
        const tw = 0.18 * pw + 0.82 * plateTint(body.plate, x, y, z);
        rgb[0] += (PLATE_RGB[0] - rgb[0]) * tw;
        rgb[1] += (PLATE_RGB[1] - rgb[1]) * tw;
        rgb[2] += (PLATE_RGB[2] - rgb[2]) * tw;
      }
    }
    return h;
  };

  const displace = flat ? () => 0 : (x, y, z, detail) => sample(x, y, z, detail, null);
  const color = (x, y, z, out, detail) => { sample(x, y, z, detail, out); return out; };

  // Вклад кратеров отдельно — нужен проверкам.
  const craterAt = flat || craterW === 0
    ? () => 0
    : (x, y, z, detail) => craterW *
      craterField(seed + CRATER_SEED, x, y, z, (detail || FULL).cs, mare(x, y, z));

  const heightNorm = (x, y, z, oct) => normOf(flat ? 0 : raw(x, y, z, oct || FULL.oct));

  // Насколько высота при детализации `coarse` может отличаться от полной.
  // Нужно рендеру: по этой границе решается, перекрывают ли подробные
  // заплатки грубую сферу (см. js/gl/patches.js).
  // Граница хвоста горного слоя: сумма амплитуд октав от m до предела.
  // Хвост КОНЕЧНЫЙ — лестница обрывается на MOUNT_MAX_OCT, — и разность
  // степеней это прямо выражает: на сетке, дошедшей до предела, граница
  // обращается в ноль, а не остаётся «почти нулём».
  const mountGap = (m, oct) => {
    if (!mnt) return 0;
    // На нулевой октаве гор НЕТ ВОВСЕ — ни хребтов, ни постоянного
    // сдвига подножия (MOUNT_B добавляется вместе с первой октавой, и
    // в сетке, и в шейдере). Значит, разойтись с полной высотой можно
    // на всю гору целиком, а не на хвост её октав. Проверка поймала
    // ровно это: шестикилометровая гора против границы в три.
    const tail = m <= 0
      ? mnt.amp * (MOUNT_K * MOUNT_TAIL + MOUNT_B)
      : (m < MOUNT_MAX_OCT
        ? mnt.amp * MOUNT_K * MOUNT_TAIL * (GAIN ** m - GAIN ** MOUNT_MAX_OCT)
        : 0);
    // Второе слагаемое — про ПОДНОЖИЕ. Горы гаснут у воды по базовому
    // шуму (MOUNT_RISE), а базовый шум на грубой сетке сам посчитан с
    // ошибкой: значит, у берега гора целиком может оказаться то выше,
    // то ниже — не на хвост своих октав, а на всю высоту, умноженную на
    // сдвиг подножия. Проверка это и поймала: без слагаемого
    // расхождение вылезало за границу вдвое, а на границе стоят юбки
    // заплаток — то есть дырки в грунте на просвет.
    //
    // Множитель 1.5 — наибольшая крутизна smooth01, 1.1 — перелёт
    // шума Перлина (см. detailGap ниже, та же пара).
    const foot = mnt.amp * (MOUNT_K * MOUNT_TAIL + MOUNT_B)
      * 1.5 * 1.1 * GAIN ** oct / MOUNT_RISE;
    return tail + foot;
  };

  const detailGap = (coarse) => {
    if (flat) return 0;
    const c = coarse || FULL;
    // Сумма амплитуд неучтённых октав: Σ(o >= n) g^o·(1-g)·1.1 = 1.1·g^n.
    const noise = cfg.amp * 1.1 * (cfg.ridge ? 1.6 : 1) * GAIN ** c.oct / span;
    const cr = craterW > 0 && c.cs < CRATER_MAX_SCALES
      ? craterBound(c.cs, -1) * craterW
      : 0;
    return noise + cr + mountGap(c.moct, c.oct);
  };

  /**
   * Реалистичная оценка ошибки сетки с такой детализацией — по ней
   * выбирается уровень плиток (js/gl/tiles.js).
   *
   * От detailGap отличается намеренно: тот даёт ГРАНИЦУ сверху («как
   * будто все неучтённые масштабы сложились в одной точке») и нужен
   * юбкам. Для выбора уровня такая оценка завышена в разы, и дерево
   * дробится куда глубже, чем нужно глазу: здесь считается самая
   * крупная неучтённая деталь, а не сумма всех.
   */
  const meshError = (coarse) => {
    if (flat) return 0;
    const c = coarse || FULL;
    const noise = cfg.amp * 1.1 * (cfg.ridge ? 1.6 : 1) * GAIN ** c.oct / span;
    let cr = 0;
    if (craterW > 0 && c.cs < CRATER_MAX_SCALES) {
      const cScale = CRATER_C0 * CRATER_STEP ** c.cs;
      cr = craterDepth((CRATER_RMIN + CRATER_RSPAN) * cScale) * craterW;
    }
    // Самая крупная неучтённая октава хребтов, а не сумма всех: здесь
    // нужна оценка, а не граница (см. коммент к meshError выше).
    const mo = mnt && c.moct < MOUNT_MAX_OCT
      ? mnt.amp * MOUNT_K * 0.5 * (1 - GAIN) * 1.6 * GAIN ** c.moct
      : 0;

    return noise + cr + mo;
  };

  const ampUp = flat ? 0 : cfg.amp + craterW * craterBound(0, +1)
    + (mnt ? mnt.amp * (MOUNT_K * MOUNT_TAIL + MOUNT_B) : 0);
  const ampDown = flat ? 0 : craterW * craterBound(0, -1);

  /**
   * Числа, по которым фрагментный шейдер считает тот же рельеф, что и
   * CPU (js/gl/detail.js). Шейдер добавляет к сетке ровно те октавы и
   * масштабы кратеров, которые в неё не вошли, поэтому сумма
   * «геометрия + шейдер» не зависит от уровня LOD.
   */
  const shaderParams = () => ({
    seed,
    amp: cfg.amp,
    span,
    freq: cfg.freq,
    ridge: cfg.ridge ? 1 : 0,
    craterW,
    flat,
    // Горный слой: ноль в амплитуде означает «гор на этом теле нет», и
    // тогда шейдер пропускает весь цикл целиком — ветвление у него
    // одинаковое на всю поверхность, то есть бесплатное.
    mount: mnt
      ? { seed: (seed + MOUNT_SEED) | 0, amp: mnt.amp, freq: mnt.freq,
        thr: mnt.thr, soft: mnt.soft, spread: mnt.spread, sea: cfg.sea }
      : null,
    // Площадка нужна и шейдеру: он досчитывает мелкий рельеф поверх
    // сетки, и без неё на срезанной плите проступали бы камни и валы,
    // которых там уже нет.
    plate: body.plate || null,
  });

  return {
    amp: cfg.amp,
    ampUp,                 // максимум смещения наружу (в долях радиуса)
    ampDown,               // максимум смещения внутрь
    detailForCell,
    shaderParams,
    meshError,
    craterDensity: flat || craterW === 0 ? () => 0 : mare,
    // Горы наружу: по ним проверяется согласие с шейдером, и по ним же
    // растительность решает, где склон, а где равнина.
    mountBelt: belt,
    // Место на рампе — по нему растительность решает, где земля зелёная.
    soil: (x, y, z, detail) => {
      if (flat) return 0;
      const d = detail || FULL;
      const r = raw(x, y, z, d.oct);
      return rampPos(x, y, z, r, mnt ? mountains(x, y, z, d.moct, r) : 0);
    },
    // Высота горы в полную силу — по ней растительность считает
    // снеговую линию, а рампа — подкраску гребней.
    mountMax: mnt ? mountMax : 0,
    hasFlora: !!cfg.flora && !flat,
    mountainAt: (x, y, z, detail) => {
      if (!mnt || flat) return 0;
      const d = detail || FULL;
      return mountains(x, y, z, d.moct, raw(x, y, z, d.oct));
    },
    hasMountains: !!mnt,
    FULL,
    sample,
    displace,
    color,
    craterAt,
    heightNorm,
    detailGap,
    isFlat: flat,
    seed,
    kindCfg: cfg,
  };
}
