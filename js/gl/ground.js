// Фотография грунта под ногами: то, что мельче процедурного предела.
//
// Зачем. Весь рельеф в игре считается от НАПРАВЛЕНИЯ, а направление в
// шейдере — float32: у единицы шаг 6e-8, то есть на планете в четыре
// тысячи километров соседние различимые точки стоят в четверти метра.
// Отсюда предел js/gl/detail.js (DETAIL_MIN_SCALE = 5e-6 рад — на Lave II
// это 21 метр): ниже него решётка шума начинает проступать ступеньками,
// и считать там нечего. Октавы тут ни при чём — сколько их ни добавляй,
// упрутся в то же самое. Поэтому с восьмидесяти метров под кораблём
// лежит гладкая крашеная плоскость.
//
// Фотография этот предел обходит тем, что ПОВТОРЯЕТСЯ: её координата
// отсчитывается не от центра планеты, а от угла плитки (grainUv ниже),
// и на сотню метров вокруг камеры точности хватает на сантиметры.
//
// Две ступени — они и в исходниках разные, это не подгонка (реальный
// размер снятого куска отдаёт Poly Haven, сверяет tools/ground.mjs):
//
//   grain, 3 м  — гравий, трещины, камешки. Нормаль и тон;
//   tint,  90 м — валуны и проплешины с дрона. Только цвет.
//
// Это КРАСКА, а не рельеф: ни посадка, ни столкновения, ни высота под
// кораблём её не видят (сантиметровый камешек им и не нужен). Всё, что
// меняет фотография, — нормаль и цвет пикселя.
//
// Цвет лежит ОТНОШЕНИЕМ к собственному среднему, а не как есть: землю
// красит мир, на котором она лежит, а не фотограф (то же правило, что у
// растительности — см. CREDITS.md). Поэтому на ледяном мире те же
// пятна выйдут голубыми, а на луне серыми.

import { CUBE_FACES } from './bake.js';

/**
 * Слои. sizeKm — РЕАЛЬНЫЙ размер снятого куска; на нём держится всё
 * остальное, и сверяется он с источником при перегоне (tools/ground.mjs).
 */
export const GROUND = {
  // low — на сколько клеток делится кусок при ОТРЕЗАНИИ НИЗКИХ ЧАСТОТ
  // (tools/ground.mjs). Восемь клеток на три метра — это 37 см: всё,
  // что крупнее, из фотографии вычитается.
  //
  // Причина не в красоте, а в повторе. Фотография укладывается через
  // три метра, и её крупные пятна повторяются вместе с ней: с
  // восьмидесяти метров это читалось ровной косой решёткой на всю
  // землю. Мелкая крошка так не читается — у неё нет узнаваемой формы,
  // и вдали она честно усредняется в ничто (верхние мип-уровни).
  grain: { file: 'assets/texture/grain.png', sizeKm: 0.003, px: 256, low: 16 },
  tint: { file: 'assets/texture/tint.png', sizeKm: 0.09, px: 128 },
  // Фактура камня (js/gl/rocks.js, tools/rocks.mjs): поверхность валуна,
  // 1.8 м. Тот же вид, что у зерна, — нормаль и тон, без цвета. Крупные
  // пятна вычитаются мельче, чем у грунта (low 4 — всё больше 45 см):
  // камень смотрят с пары метров, и его рисунок должен остаться.
  rock: { file: 'assets/texture/rock.png', sizeKm: 0.0018, px: 256, low: 4 },
};

/**
 * Пятна берутся ДВАЖДЫ: своим размером и ещё раз крупнее, повёрнутыми
 * на прямой угол. Одна выборка повторяется через девяносто метров, и на
 * открытой равнине это видно решёткой — так и вышло на первом снимке.
 * Две выборки с несоизмеримым шагом дают период в два с половиной
 * километра: столько открытой земли в кадр не помещается.
 *
 * Число нецелое намеренно: при целом обе решётки совпали бы узлами, и
 * решётка осталась бы на месте.
 */
export const TINT_WIDE = 2.7;

// Сила слоёв. Единица — «как снято»: наклон нормали настоящий, тон и
// цвет отклоняются ровно так же, как на фотографии.
export const GRAIN_BUMP = 1.0;
export const GRAIN_TONE = 0.7;
// Единица у пятен оказалась перебором: при ней аэрофото красит грунт
// своей сыпью, а не подкрашивает его. 0.7 — это разброс по синему
// каналу около 12%, то есть «местами посерее, местами позеленее».
export const TINT_K = 0.7;

// Дальше этого размаха координату зерна считать нельзя: она приходит в
// шейдер как float32, и на размахе в миллион плиток у неё пропадает
// дробная часть — узор пошёл бы квадратами по четверти плитки. Предел
// взят из точности: 6e-8 (шаг float32 у единицы) * размах должен
// остаться мельче тексели, то есть 1/256 плитки.
export const GRAIN_MAX_SPAN = 1 / 256 / 6e-8;      // ~65 тысяч плиток

/**
 * Плиток зерна на единицу координаты грани куба.
 *
 * Грань параметризована как в js/gl/quadtree.js (faceDir): su и sv идут
 * от -1 до 1, и вдоль оси это ровно четверть прямого угла на единицу.
 * Значит дуга на единицу su — это R * pi/4.
 */
export const grainPerUnit = (radiusKm, sizeKm) => radiusKm * Math.PI / 4 / sizeKm;

/**
 * Начало отсчёта для одного вызова отрисовки.
 *
 * Возвращает дробные части координаты зерна и пятен в углу меша. Дробные
 * — потому что обе текстуры повторяются с периодом 1, и целые плитки в
 * шейдер посылать незачем: там они и потеряются. Считается это в double
 * на процессоре, поэтому шов между соседними мешами сходится точно.
 *
 * @param radiusKm радиус тела
 * @param su,sv    координата УГЛА меша на грани куба (-1..1)
 */
export function grainOrigin(radiusKm, su, sv, out = [0, 0, 0, 0, 0, 0]) {
  const kg = grainPerUnit(radiusKm, GROUND.grain.sizeKm);
  const kt = grainPerUnit(radiusKm, GROUND.tint.sizeKm);
  const kw = kt / TINT_WIDE;
  const fr = (v) => v - Math.floor(v);
  out[0] = fr(su * kg); out[1] = fr(sv * kg);
  out[2] = fr(su * kt); out[3] = fr(sv * kt);
  // Широкая выборка повёрнута: (u, v) -> (v, -u). Поворот применяется и
  // к началу отсчёта, и к смещению в шейдере — иначе они разъедутся.
  out[4] = fr(sv * kw); out[5] = fr(-su * kw);
  return out;
}

/**
 * Грань куба, на которой лежит направление, и координаты на ней.
 *
 * Нужно заплаткам: они центрированы на камере, а не на решётке куба, и
 * своей координаты на грани у них нет. Грань берётся ОДНА на весь набор
 * — по его центру, — и продолжается за свои 45° как есть: заплатка
 * маленькая, искажение на её краю пренебрежимо, зато узор не рвётся на
 * ребре куба.
 */
export function faceCoords(face, x, y, z) {
  const f = CUBE_FACES[face];
  const w = f.F[0] * x + f.F[1] * y + f.F[2] * z;
  if (w <= 1e-6) return null;                  // за горизонтом грани
  const u = (f.U[0] * x + f.U[1] * y + f.U[2] * z) / w;
  const v = (f.V[0] * x + f.V[1] * y + f.V[2] * z) / w;
  const q = 4 / Math.PI;
  return { su: Math.atan(u) * q, sv: Math.atan(v) * q };
}

/** Какая грань куба ближе всего к направлению. */
export function faceOf(x, y, z) {
  let best = 0, dot = -2;
  for (let i = 0; i < 6; i++) {
    const f = CUBE_FACES[i];
    const d = f.F[0] * x + f.F[1] * y + f.F[2] * z;
    if (d > dot) { dot = d; best = i; }
  }
  return best;
}

// --- Шейдер ------------------------------------------------------------------

const f = (x) => {
  const s = String(x);
  return s.includes('.') || s.includes('e') ? s : s + '.0';
};

/**
 * Обе ступени фотографии — одной функцией.
 *
 * Координата приходит готовой (vGrain, в плитках зерна от угла меша), а
 * начало отсчёта — uniform-ом: складываются они уже здесь, и дробная
 * часть при этом не теряется. Считать координату в шейдере от
 * направления НЕЛЬЗЯ — ровно та же потеря точности, из-за которой
 * процедурный рельеф упирается в два десятка метров.
 *
 * uGrainOn = 0 — фотографии нет (корабли, станции, слишком грубая
 * плитка), и весь блок пропускается одним сравнением.
 */
export const GRAIN_GLSL = `
uniform sampler2D uGrainTex;   // зерно: нормаль (RG) и тон (B)
uniform sampler2D uTintTex;    // пятна: цвет к собственному среднему
uniform vec4 uGrainOrg;        // начало отсчёта: зерно .xy, пятна .zw
uniform vec2 uTintOrg2;        // оно же у широкой выборки пятен
uniform vec3 uGrainU;          // оси параметризации в осях тела
uniform vec3 uGrainV;
uniform float uGrainOn;

const float D_TINT_STEP = ${f(GROUND.grain.sizeKm / GROUND.tint.sizeKm)};
const float D_TINT_WIDE = ${f(TINT_WIDE)};
const float D_GRAIN_BUMP = ${f(GRAIN_BUMP)};
const float D_GRAIN_TONE = ${f(GRAIN_TONE)};
const float D_TINT_K = ${f(TINT_K)};

void groundPhoto(vec3 dirL, vec2 g, mat3 nm, float w, inout vec3 n, inout vec3 albedo) {
  vec3 s = texture(uGrainTex, uGrainOrg.xy + g).rgb;
  // Пятна — двумя выборками с несоизмеримым шагом, иначе на равнине
  // видна решётка в девяносто метров (см. TINT_WIDE).
  vec3 c = texture(uTintTex, uGrainOrg.zw + g * D_TINT_STEP).rgb
         + texture(uTintTex,
             uTintOrg2 + vec2(g.y, -g.x) * (D_TINT_STEP / D_TINT_WIDE)).rgb;
  // Оси параметризации постоянные (это оси грани куба), а поверхность
  // под ними кривая — поэтому на месте приводим их к касательной.
  vec3 gu = normalize(uGrainU - dirL * dot(dirL, uGrainU));
  vec3 gv = normalize(uGrainV - dirL * dot(dirL, uGrainV));
  vec2 t = (s.xy * 2.0 - 1.0) * (D_GRAIN_BUMP * w);
  n = normalize(n + nm * (gu * t.x + gv * t.y));
  albedo *= mix(1.0, s.z * 2.0, D_GRAIN_TONE * w);
  // Два текселя по 0.5 в среднем дают ровно единицу — это уже среднее
  // отношение, поэтому разворачивать его обратно (x2) больше не нужно.
  albedo *= mix(vec3(1.0), c, D_TINT_K * w);
}
`;

// --- Загрузка ----------------------------------------------------------------

/**
 * Нейтральный тексель: нормаль (0, 0) и отношение 1.0 — то есть «ничего
 * не менять». Один и тот же для обоих слоёв, поэтому сцена работает
 * ровно так же, если картинки не загрузились вовсе (нет файла, нет
 * сети, запрет на выборку): грунт просто останется прежним.
 */
const NEUTRAL = new Uint8Array([128, 128, 128, 255]);

function makeTexture(gl) {
  const tex = gl.createTexture();
  gl.bindTexture(gl.TEXTURE_2D, tex);
  gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA, 1, 1, 0, gl.RGBA, gl.UNSIGNED_BYTE, NEUTRAL);
  // Повтор обязателен: плитка укладывается на планету миллионы раз.
  gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_S, gl.REPEAT);
  gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_T, gl.REPEAT);
  gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.LINEAR);
  gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, gl.LINEAR);
  gl.bindTexture(gl.TEXTURE_2D, null);
  return tex;
}

/**
 * Обычная загрузка картинки. Вне браузера (проверки в node) Image нет
 * вовсе — это не ошибка, а «картинок не будет»: текстуры останутся
 * нейтральными, и сцена соберётся ровно так же.
 */
const defaultLoad = (src, on, fail) => {
  if (typeof Image === 'undefined') { fail(); return; }
  const img = new Image();
  img.onload = () => on(img);
  img.onerror = fail;
  // Метка загрузки — та же, что у модулей (cache.js). Без неё браузер
  // отдаёт старую картинку из кеша, и пересобранная текстура не
  // появляется до ручной очистки: перегон вроде бы отработал, а в
  // кадре всё по-прежнему.
  const v = typeof window !== 'undefined' && window.__srcStamp;
  img.src = v ? `${src}?v=${v}` : src;
};

/**
 * Обе текстуры грунта. Возвращаются СРАЗУ, заполненные нейтральным
 * текселем, а картинки подставляются, когда догрузятся: ждать их в
 * первом кадре незачем — до земли ещё лететь.
 *
 * Мипы строятся при загрузке и делают всю работу по затуханию: вдали
 * тексель мельче пикселя, выборка уходит в верхний уровень, а верхний
 * уровень — это среднее, то есть ровно «ничего не менять». Поэтому
 * отдельной ручки «докуда показывать зерно» нет и не нужно.
 */
export function loadGround(gl, load = defaultLoad) {
  const out = { grain: makeTexture(gl), tint: makeTexture(gl), rock: makeTexture(gl), ready: 0, failed: 0 };
  for (const key of ['grain', 'tint', 'rock']) {
    load(GROUND[key].file, (img) => {
      gl.bindTexture(gl.TEXTURE_2D, out[key]);
      gl.pixelStorei(gl.UNPACK_FLIP_Y_WEBGL, false);
      gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA, gl.RGBA, gl.UNSIGNED_BYTE, img);
      gl.generateMipmap(gl.TEXTURE_2D);
      gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.LINEAR_MIPMAP_LINEAR);
      gl.bindTexture(gl.TEXTURE_2D, null);
      out.ready++;
    }, () => { out.failed++; });
  }
  return out;
}
