// Язык игры: английский и русский.
//
// Ключом перевода служит САМА РУССКАЯ СТРОКА, а не выдуманный
// идентификатор вроде `hud.scanner.peers`. Причина простая: с
// идентификаторами исходник перестаёт читаться — вместо надписи в коде
// стоит ссылка, и чтобы понять, что нарисует прибор, надо лезть в
// словарь. А ещё их надо придумывать, и придумывают их по-разному два
// раза подряд. С русским ключом строка видна на месте, а перевод лежит
// рядом в одном файле.
//
// Плата за это честная: поправил надпись по-русски — поправь ключ в
// словаре. Ровно это и проверяется (tools/test.mjs): каждая русская
// строка в игровых файлах обязана иметь перевод, иначе проверка падает.
// Без такой проверки перевод разъезжается с игрой за неделю.
//
// Не переведено намеренно: отладочный оверлей (`~`). Это инструмент
// разработки, а не игры, и держать его в двух видах — работа без отдачи.

import { EN } from './lang.en.js';

export const LANGS = { en: 'ENGLISH', ru: 'РУССКИЙ' };

const KEY = 'solar_lang';

let lang = 'en';

/** Прочитать выбор игрока. Нет выбора — английский. */
export function initLang() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && LANGS[saved]) lang = saved;
  } catch (e) { /* приватный режим: живём с языком по умолчанию */ }
  return lang;
}

export const getLang = () => lang;

export function setLang(code) {
  if (!LANGS[code]) return lang;
  lang = code;
  try { localStorage.setItem(KEY, code); } catch (e) { /* и без памяти сойдёт */ }
  return lang;
}

/**
 * Перевод.
 *
 * Русский возвращается как есть — он и есть ключ. Если перевода нет,
 * возвращается тоже русский: непереведённая надпись хуже переведённой,
 * но куда лучше пустого места на приборе.
 */
export function L(ru) {
  if (lang === 'ru') return ru;
  const en = EN[ru];
  return en === undefined ? ru : en;
}

/**
 * Как форматировать числа.
 *
 * Разряды в русском разделяются пробелом, в английском запятой: «12 345»
 * против «12,345». Мелочь, по которой сразу видно, что перевод делали
 * наполовину.
 */
export const numLocale = () => (lang === 'ru' ? 'ru-RU' : 'en-US');

/** Есть ли перевод — для проверок. */
export const hasEn = (ru) => Object.prototype.hasOwnProperty.call(EN, ru);
