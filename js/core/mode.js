// Как запущена игра: с сервером или сама по себе.
//
// Отдельным модулем, потому что спрашивают в двух местах и ответ обязан
// быть один. Загрузчик (js/boot.js) решает по нему, идти ли за
// характеристиками на сервер, а игра (js/main.js) — входить ли в сеть.
// Пока правило было выписано в обоих, достаточно было поправить его в
// одном, чтобы игра пошла за числами к серверу, которого нет.

const q = () => new URLSearchParams(location.search);

/** Режим разработки: `?dev=1`. Включает и автономность заодно. */
export const devMode = () => q().get('dev') === '1';

/** Игра без сервера: `?offline=1` или `?dev=1`. */
export const soloMode = () => q().get('offline') === '1' || devMode();
