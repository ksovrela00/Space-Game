// Загрузчик: получить характеристики и только потом запустить игру.
//
// Отдельный файл нужен из-за порядка. Игра собирает корабль прямо при
// разборе своего модуля (`const ship = makeShip()`), и к этому моменту
// числа обязаны быть на месте — иначе корабль соберётся из пустоты. А
// числа теперь приходят из бэкенда, то есть ожиданием. Поставить
// ожидание внутрь main.js нельзя: его модуль уже разбирается.
//
// Поэтому точка входа страницы — этот файл, и игра грузится после того,
// как характеристики разложены (js/game/specs.js).

import { soloMode } from './core/mode.js';
import { loadSpecs } from './game/specs.js';
import { L, initLang } from './core/lang.js';

// Язык — до первой надписи: единственное, что этот файл может сказать
// игроку, это «не загрузилось», и сказать это он обязан на его языке.
initLang();

/**
 * Сказать, что запуск не состоялся.
 *
 * Без этого при недоступных числах игрок видел бы чёрный экран и должен
 * был бы лезть в консоль, чтобы узнать хоть что-то. А случай вполне
 * обычный: сервер не поднят, базы нет, каталог не залит.
 */
function fail(err) {
  const body = document.getElementById('bootBody');
  const text = L('ХАРАКТЕРИСТИКИ КОРАБЛЯ НЕ ЗАГРУЖЕНЫ: ') + (err && err.message ? err.message : err);
  const hint = L('Поднимите сервер или соберите слепок: ') + 'php server/cli/specs.php';
  if (body) {
    body.innerHTML = '<p style="color:#ff7a66">' + text + '</p><p class="sub">' + hint + '</p>';
    const btn = document.getElementById('bootBtn');
    if (btn) btn.style.display = 'none';
  }
  console.error(text, err);
}

try {
  const { error } = await loadSpecs({ offline: soloMode() });
  // Числа из слепка вместо сервера — не отказ, но и не норма: игра
  // полетит по последним выгруженным. Говорим об этом вслух, иначе
  // «почему у меня другой урон» выясняется в бою.
  if (error) console.warn(L('характеристики взяты из слепка: ') + error.message);
  await import('./main.js');
} catch (e) {
  fail(e);
}
