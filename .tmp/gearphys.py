import io

p = 'js/game/ship.js'
s = io.open(p, encoding='utf-8').read()

old = """  // С выпущенным шасси корабль переходит в посадочную конфигурацию:
  // главные движки работают ТОЛЬКО по горизонту, а вертикаль остаётся
  // тяготению и подъёмным движкам. Иначе тяга, отрабатывая «остановись»,
  // съедала бы и падение — гравитация переставала бы чувствоваться ровно
  // там, где она и нужна.
  const f = ship.basis.fwd, u = ship.basis.up;
  const gearOut = !!(ship.gear && ship.gear.t > 0.02);
  const free = !!field && gearOut;
  const up = field ? field.up : null;
  const g = field ? field.g : 0;

  // Ось подъёмных движков: в посадочной конфигурации это местная
  // вертикаль (по ней же работает тяготение), иначе — «верх» самого
  // корабля, то есть ровно то, куда движки толкают.
  const la = free ? up : u;
  // Вертикаль считается отдельным каналом — и в посадочной
  // конфигурации, и всегда, пока отклонена ручка подъёмных движков.
  // Иначе их тяга бессмысленна: гашение заноса ниже видит набранную
  // вертикальную скорость как снос и стирает её в следующем же кадре
  // (0.5 км/с² против 0.004), и R/F не делают ровно ничего.
  const liftOn = free || c.lift !== 0;"""

new = """  // ШАССИ НЕ МЕНЯЕТ УПРАВЛЕНИЕ. Оно меняет одно — предел скорости.
  //
  // Раньше его выпуск переключал модель полёта целиком: выключался
  // компенсатор высоты (корабль начинал проваливаться сам), а главные
  // движки переставали толкать вверх и работали только по горизонту.
  // Задумано это было как «почувствовать вес на посадке», а на деле
  // читалось как поломка: одна клавиша — и корабль перестаёт слушаться
  // так, как слушался секунду назад. Ни один аппарат от выпуска стоек
  // так себя не ведёт.
  //
  // Теперь компенсатор высоты работает ВСЕГДА: движки держат корабль
  // против местной тяжести, и с нулевой ручкой он висит на месте на
  // любой высоте и с любым шасси. Тяжесть от этого не исчезает — она
  // по-прежнему задаёт силу подъёмных движков (SHIP.liftTWR), решает
  // исход удара и работает в полную силу, пока корабль оглушён (см.
  // выше: там нет ни тяги, ни стабилизации).
  const f = ship.basis.fwd, u = ship.basis.up;
  const gearOut = !!(ship.gear && ship.gear.t > 0.02);
  const up = field ? field.up : null;
  const g = field ? field.g : 0;

  // Ось подъёмных движков — «верх» самого корабля, то есть ровно то,
  // куда они толкают.
  const la = u;
  // Вертикаль считается отдельным каналом, пока отклонена ручка
  // подъёмных движков. Иначе их тяга бессмысленна: гашение заноса ниже
  // видит набранную вертикальную скорость как снос и стирает её в
  // следующем же кадре (0.5 км/с² против 0.004), и R/F не делают ровно
  // ничего.
  const liftOn = c.lift !== 0;"""
assert old in s
s = s.replace(old, new)

old2 = """  // Направление тяги: нос, а в посадочной конфигурации — его проекция на
  // горизонт. У самого зенита проекция вырождается, и тяги просто нет.
  let fx = f.x, fy = f.y, fz = f.z;
  if (free) {
    const fu = f.x * up.x + f.y * up.y + f.z * up.z;
    fx -= up.x * fu; fy -= up.y * fu; fz -= up.z * fu;
    const fl = Math.hypot(fx, fy, fz);
    if (fl > 0.08) { fx /= fl; fy /= fl; fz /= fl; } else { fx = fy = fz = 0; }
  }
"""
new2 = """  // Направление тяги — всегда нос, независимо от шасси.
  const fx = f.x, fy = f.y, fz = f.z;
"""
